/**
 * A transaction's `insertMany` and `updateMany` (adapters/adapter.ts): each is one statement however many rows it
 * carries, answers in the order it was asked, and refuses what the single-row form refuses, by the same words.
 *
 * RETURNING promises no order on either engine, so the rows are matched back by their values; a key named twice
 * in one update is refused rather than left to whichever CASE arm the engine reads first; a guarded row that moved
 * is a WriteConflict and the batch rolls back whole. SQLite always; PostgreSQL when `TABLEWALK_TEST_PG` names a
 * disposable server (the schema `batch_writes`, dropped before and after).
 */
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { after, before, describe, test } from 'node:test';
import { insertAll, updateAll, WriteConflict, type WriteTransaction } from '../packages/engine/src/adapters/adapter.js';
import { PostgresAdapter } from '../packages/engine/src/adapters/postgres.js';
import { SqliteAdapter } from '../packages/engine/src/adapters/sqlite.js';
import { liveSkip } from './live.js';

const LIVE = process.env.TABLEWALK_TEST_PG;
const SCHEMA = 'batch_writes';

type Row = Record<string, unknown>;
interface World {
  readonly table: string;
  readonly adapter: SqliteAdapter | PostgresAdapter;
  rows(): Promise<Row[]>;
  close(): Promise<void>;
}

function statements(postgres: boolean): string[] {
  const pk = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  return [
    `CREATE TABLE bin (id ${pk}, sku TEXT NOT NULL, qty INTEGER NOT NULL DEFAULT 0, note TEXT)`,
    `INSERT INTO bin (id, sku, qty) VALUES (1, 'a', 1), (2, 'b', 2), (3, 'c', 3)`,
  ];
}

async function sqliteWorld(): Promise<World> {
  const directory = mkdtempSync(join(tmpdir(), 'mistri-batch-'));
  const file = join(directory, 'data.db');
  const db = new DatabaseSync(file);
  for (const statement of statements(false)) db.exec(statement);
  const adapter = new SqliteAdapter(file, 'batch');
  return {
    table: 'bin',
    adapter,
    rows: async () => db.prepare('SELECT * FROM bin ORDER BY id').all() as Row[],
    async close() {
      await adapter.close();
      db.close();
      rmSync(directory, { recursive: true, force: true });
    },
  };
}

async function postgresWorld(): Promise<World> {
  const specifier = 'pg';
  const pg = (await import(specifier)) as { default?: { Client: never }; Client?: never };
  const Client = (pg.Client ?? pg.default?.Client)! as new (c: unknown) => {
    connect(): Promise<void>;
    query(sql: string, params?: readonly unknown[]): Promise<{ rows: Row[] }>;
    end(): Promise<void>;
  };
  const control = new Client({ connectionString: LIVE, statement_timeout: 60_000 });
  await control.connect();
  await control.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE; CREATE SCHEMA ${SCHEMA}`);
  await control.query(`SET search_path TO ${SCHEMA}`);
  for (const statement of statements(true)) await control.query(statement);
  const adapter = new PostgresAdapter(LIVE!, 'batch', [SCHEMA]);
  return {
    table: `${SCHEMA}.bin`,
    adapter,
    rows: async () => (await control.query(`SELECT * FROM ${SCHEMA}.bin ORDER BY id`)).rows,
    async close() {
      await adapter.close();
      await control.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await control.end();
    },
  };
}

/** Each statement the transaction runs, by the text of its result: a batch answers every row with one. */
const statementsOf = (results: readonly { sql: { text: string } }[]) => new Set(results.map((result) => result.sql.text)).size;
const plain = (rows: readonly Row[]) =>
  rows.map((row) => ({ id: Number(row.id), sku: row.sku, qty: Number(row.qty), note: row.note ?? null }));

function proofs(open: () => Promise<World>, label: string, skip: false | string = false) {
  describe(`a batch write on ${label}`, { skip }, () => {
    let w: World;
    before(async () => {
      w = await open();
      await w.adapter.introspect();
    });
    after(async () => {
      await w?.close();
    });

    const within = <T>(run: (tx: WriteTransaction) => Promise<T>) => w.adapter.transaction(run);

    test('the transaction offers both batch forms', async () => {
      await within(async (tx) => {
        assert.equal(typeof tx.insertMany, 'function');
        assert.equal(typeof tx.updateMany, 'function');
      });
    });

    test('insertMany is one statement and answers each row in the order it was asked', async () => {
      const results = await within((tx) =>
        insertAll(tx, [
          { table: w.table, values: { sku: 'x', qty: 7 } },
          { table: w.table, values: { sku: 'y', qty: 7 } },
          { table: w.table, values: { sku: 'z', qty: 9, note: 'last' } },
        ]),
      );
      assert.deepEqual(
        results.map((result) => result.row?.sku),
        ['x', 'y', 'z'],
      );
      assert.equal(statementsOf(results.slice(0, 2)), 1, 'rows with the same columns share one statement');
      const keys = results.map((result) => Number(result.key.id));
      assert.equal(new Set(keys).size, 3);
      const stored = plain(await w.rows()).filter((row) => keys.includes(row.id));
      assert.deepEqual(
        keys.map((key) => stored.find((row) => row.id === key)?.sku),
        ['x', 'y', 'z'],
      );
    });

    test('updateMany is one statement, guarded per row', async () => {
      const results = await within((tx) =>
        updateAll(tx, [
          { table: w.table, key: { id: 2 }, values: { qty: 20 }, expected: { qty: 2 } },
          { table: w.table, key: { id: 1 }, values: { qty: 10, note: 'one' } },
          { table: w.table, key: { id: 3 }, values: { qty: 30 } },
        ]),
      );
      assert.deepEqual(
        results.map((result) => result.affected),
        [1, 1, 1],
      );
      assert.equal(statementsOf(results), 1);
      assert.deepEqual(
        plain(await w.rows())
          .filter((row) => row.id <= 3)
          .map((row) => [row.id, row.qty, row.note]),
        [
          [1, 10, 'one'],
          [2, 20, null],
          [3, 30, null],
        ],
      );
    });

    test('a guarded row that moved is a WriteConflict, and the whole batch rolls back', async () => {
      const before = plain(await w.rows());
      await assert.rejects(
        within((tx) =>
          updateAll(tx, [
            { table: w.table, key: { id: 1 }, values: { qty: 11 } },
            { table: w.table, key: { id: 2 }, values: { qty: 21 }, expected: { qty: 999 } },
          ]),
        ),
        (error) => error instanceof WriteConflict,
      );
      assert.deepEqual(plain(await w.rows()), before);
    });

    test('a key that names no row is refused as the single-row form refuses it', async () => {
      await assert.rejects(
        within((tx) =>
          updateAll(tx, [
            { table: w.table, key: { id: 1 }, values: { qty: 12 } },
            { table: w.table, key: { id: 404 }, values: { qty: 12 } },
          ]),
        ),
        /matches 0 rows/,
      );
    });

    test('a key named twice in one update is refused', async () => {
      await assert.rejects(
        within((tx) =>
          updateAll(tx, [
            { table: w.table, key: { id: 1 }, values: { qty: 13 } },
            { table: w.table, key: { id: 1 }, values: { note: 'again' } },
          ]),
        ),
        /twice/,
      );
    });

    test('an insert the database refuses rolls the batch back whole', async () => {
      const before = plain(await w.rows());
      await assert.rejects(
        within((tx) =>
          insertAll(tx, [
            { table: w.table, values: { sku: 'ok', qty: 1 } },
            { table: w.table, values: { sku: null, qty: 1 } },
          ]),
        ),
      );
      assert.deepEqual(plain(await w.rows()), before);
    });
  });
}

proofs(sqliteWorld, 'SQLite');
proofs(postgresWorld, 'PostgreSQL', liveSkip('postgres', LIVE));
