#!/usr/bin/env node
/**
 * The App DSL reference, generated.
 *
 * A hand-written key reference drifted from packages/mistri/schema/app.schema.json and from
 * the public-surface inventory. This reads both: the inventory
 * (test/fixtures/public-surface.json) says which names are public and which
 * are preview; the schemas say what each is (type, values, default,
 * description); the sample Apps say where each is first used. One page per
 * top-level group, dsl-<group>.md, and an index, app-dsl.md, are written
 * beside the site's other pages (site/src/content/docs/docs/), so the package
 * ships them and `mistri docs dsl-views` reads them offline. What a table
 * cannot say (a worked example, how the keys combine) is written by hand in
 * site/reference-notes/<group>.md and set above the page's tables.
 *
 *   node scripts/dsl-reference.mjs           regenerate the pages
 *   node scripts/dsl-reference.mjs --check   fail if the committed pages differ (test/docs-site.test.ts runs this)
 *
 * It fails when a public name has no schema node, so a key cannot be
 * published without a description to print, and when a described key is not in
 * the inventory, so a key cannot be described and left unfrozen. A key is
 * "used in" the first sample App file (in the order the examples README lists
 * them) that spells it as a property, by file and without a line, so editing
 * a sample does not make the pages stale; a name found in many files points nowhere and has none.
 */
