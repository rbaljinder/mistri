/**
 * An integration's multipart callback (integrations/integrationInbound.ts): a provider that sends a file beside its
 * event signs the whole `multipart/form-data` body, `verify` reads the non-file parts as `form`, and each file part
 * lands in the mapped command's `field.files` of that name exactly as a person's upload does: the command stores it
 * with insertFile, and the field's own accept and the file resource's cap refuse what an upload would refuse. Over a
 * real loopback server on each engine.
 */
