/**
 * Writes through a narrowed resource (Preview, appNarrowed.ts, appNarrowedWrites.ts), on SQLite and, under
 * TABLEWALK_TEST_PG, on PostgreSQL: every write stays inside the resource's query.
 *
 * An insert takes the query's equalities and refuses a value that contradicts one; a query that is not plain
 * equalities takes no new row. An update may not move a row out of the query, and a row outside it answers as a
 * key nothing holds does, for an update and a delete alike. The same on every door that writes: Save and New
 * (the update and insert routes), Delete, a fixed action, a machine's step, a CSV import and a command's `tx`.
 * A notify rule on the resource tells its people about the rows its query reads and no others.
 */
