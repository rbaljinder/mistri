test('the generator writes one import-free, deterministic client from an exported document', () => {
  const first = renderApiClient(small());
  assert.equal(renderApiClient(JSON.parse(JSON.stringify(small()))), first);
  assert.doesNotMatch(first, /^\s*import\s|\brequire\(|\bDate\b|Date\.now/m);
  assert.match(first, /generated by `mistri api client`/);
  assert.match(first, /export class ApiError extends Error/);
  assert.match(first, /export type RowItem = \{/);
  assert.match(first, /id: string;/);
  assert.match(first, /note\?: string \| null;/);
  assert.match(first, /state\?: "open" \| "shut";/);
  assert.match(first, /readItemItem: \(args: \{ id: string \}\): Promise<RowItem>/);
  assert.match(first, /readListItem: \(args: \{ ifMatch: string; limit\?: number \}\): Promise<\{/);
  assert.match(first, /commandChange: \(args: \{ body: \{/);
  assert.match(first, /path: `\/item\/\$\{segment\(args\.id\)\}`/);
  assert.match(first, /"If-Match": args\.ifMatch/);
  // A title cannot close the header's comment.
  assert.ok(first.includes('Shop "Quotes" API'));
});

test('a path is text in the client, and a composite key travels as column=value pairs', () => {
  const doc = small();
  const paths = doc.paths as Record<string, unknown>;
  paths['/odd/`${globalThis.x}`/{id}'] = paths['/item/{id}'];
  const source = renderApiClient(doc);
  assert.ok(source.includes('/odd/\\`\\${globalThis.x}\\`/${segment(args.'), 'the backtick and ${ stay text');
  const segment = new Function(
    `${/function segment[\s\S]*?\n\}/.exec(source)![0].replace(/: unknown|: string|as Record<string, unknown>/g, '')}; return segment;`,
  )();
  assert.equal(segment({ id: 7, part: 'a,b' }), 'id=7,part=a%2Cb');
  assert.equal(segment('a/b'), 'a%2Fb');
});

test('the generator refuses a document mistri did not make, in one line that names the fix', () => {
  for (const bad of [null, [], { openapi: '3.1.0' }, { openapi: '3.1.0', paths: {} }, { ...small(), 'x-mistri-document': 'other' }]) {
    assert.throws(
      () => renderApiClient(bad),
      (error: Error) => /--export openapi|OpenAPI document/.test(error.message) && !error.message.includes('\n'),
    );
  }
});

test('the command refuses a missing --out and a file that is not an App API document', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'tw-api-client-'));
  try {
    const spec = join(directory, 'spec.json');
    writeFileSync(spec, JSON.stringify(small()));
    const noOut = await runCli(['api', 'client', spec]);
    assert.equal(noOut.code, 1);
    assert.match(noOut.err, /--out is required/);
    writeFileSync(join(directory, 'other.json'), JSON.stringify({ openapi: '3.1.0', info: {}, paths: {} }));
    const other = await runCli(['api', 'client', join(directory, 'other.json'), '--out', join(directory, 'c.ts')]);
    assert.equal(other.code, 1);
    assert.match(other.err, /not an App API document made by mistri/);
    const ok = await runCli(['api', 'client', spec, '--out', join(directory, 'nested', 'client.ts')]);
    assert.equal(ok.code, 0, ok.err);
    assert.equal(readFileSync(join(directory, 'nested', 'client.ts'), 'utf8'), renderApiClient(small()));
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});

/** The ledger App on SQLite, with one eligible native account and a token that may read and run its command. */
async function ledger(t: TestContext) {
  const directory = mkdtempSync(join(tmpdir(), 'tw-api-client-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const business = join(directory, 'business.db'),
    authPath = join(directory, 'auth.db');
  const db = new DatabaseSync(business);
  try {
    db.exec(`${LEDGER_TABLE}; ${LEDGER_ROW}`);
  } finally {
    db.close();
  }
  migrateSqliteCommandJournal(business);
  const { appDir, config, commands } = writeLedgerApp(directory, { business, authStore: authPath });
  const loaded = await loadApp(appDir);
  writeFileSync(join(appDir, 'authority.lock'), loaded.authority!.report);
  const names = ['BETTER_AUTH_SECRET', 'MISTRI_AUTH_ADMIN_EMAIL', 'MISTRI_AUTH_ADMIN_PASSWORD'] as const;
  const saved = names.map((name) => [name, process.env[name]] as const);
  process.env.BETTER_AUTH_SECRET = SESSION_SECRET;
  delete process.env.MISTRI_AUTH_ADMIN_EMAIL;
  delete process.env.MISTRI_AUTH_ADMIN_PASSWORD;
  try {
    (await createAppAuth(loaded, { baseURL: 'http://127.0.0.1:1', trustedOrigins: ['http://127.0.0.1:1'] })).close();
  } finally {
    for (const [name, value] of saved) {
      if (value === undefined) delete process.env[name];
      else process.env[name] = value;
    }
  }
  const accounts = new DatabaseSync(authPath);
  try {
    accounts
      .prepare('INSERT INTO "user" (id,name,email,emailVerified,createdAt,updatedAt,role,banned) VALUES (?,?,?,1,?,?,?,0)')
      .run('operator', 'Operator', 'operator@example.test', '2026-01-01T00:00:00.000Z', '2026-01-01T00:00:00.000Z', 'operator');
  } finally {
    accounts.close();
  }
  const exclusions = [captureAuthStoreExclusion(business)];
  provisionSqliteApiTokenStore(authPath, { appId: 'ledger', storeId, exclusions });
  const registry = new Registry();
  registry.add({ id: 'data', name: 'data', url: business, writable: true, source: 'config' });
  let issue: (operations?: readonly string[]) => ReturnType<typeof issueSqliteApiCommandToken>;
  try {
    const resources = await loadAppRuntimeResources(registry, loaded.app, 'data');
    const evidence = { connectionFor: resources.connectionFor, writableConnection: () => true, transactionalConnection: () => true };
    const declared = await loadBusinessCommands(commands);
    issue = (operations) =>
      issueSqliteApiCommandToken(
        authPath,
        loaded.app,
        resources.schema,
        declared,
        evidence,
        {
          storeId,
          exclusions,
          subjectId: 'operator',
          actorId: 'operator',
          roles: ['operator'],
          label: 'Client test',
          expiresAt: Date.now() + 600000,
          ...(operations ? { operations } : {}),
        },
        Date.now(),
      );
  } finally {
    await registry.closeAll();
  }
  return { directory, appDir, config, commands, issue };
}

type Generated = {
  createClient: (options: { baseUrl: string; token: string | (() => string) }) => any;
  ApiError: new (...args: any[]) => Error & { status: number; problem?: { code: string } };
};

function typecheck(file: string) {
  return new Promise<{ code: number; out: string }>((done) => {
    const tsc = resolve(ROOT, 'node_modules/typescript/bin/tsc');
    execFile(
      process.execPath,
      [
        tsc,
        '--ignoreConfig',
        '--noEmit',
        '--strict',
        '--target',
        'es2022',
        '--module',
        'esnext',
        '--moduleResolution',
        'bundler',
        '--lib',
        'es2022,dom',
        '--types',
        '',
        file,
      ],
      { timeout: 120000 },
      (error, out, err) => done({ code: Number(error?.code ?? 0), out: out + err }),
    );
  });
}

test(
  'a client written from a real App export type-checks and calls its API: a read, a command and a refusal',
  { timeout: 240000 },
  async (t) => {
    const f = await ledger(t);
    const exported = await runCli([
      '--config',
      f.config,
      '--app',
      f.appDir,
      '--commands',
      f.commands,
      '--export',
      'openapi',
      '--api-integers',
      'decimal-string',
    ]);
    assert.equal(exported.code, 0, exported.err);
    const spec = join(f.directory, 'api.json'),
      client = join(f.directory, 'client.ts');
    writeFileSync(spec, exported.out);
    const written = await runCli(['api', 'client', spec, '--out', client]);
    assert.equal(written.code, 0, written.err);
    const source = readFileSync(client, 'utf8');
    assert.equal(renderApiClient(JSON.parse(exported.out)), source);
    assert.doesNotMatch(source, /^\s*import\s/m);

    // The file stands alone, and a caller written against it is checked with it.
    const caller = join(f.directory, 'caller.ts');
    writeFileSync(
      caller,
      `import { createClient, ApiError, type ApiProblem, type ApiToken, type ClientOptions } from './client';
export async function use(baseUrl: string, token: string) {
  const lazy: ApiToken = async () => token;
  const options: ClientOptions = { baseUrl, token: lazy };
  const api = createClient(options);
  const describe = (problem: ApiProblem): string => \`\${problem.status} \${problem.code}\`;
  const row = await api.readItemItem({ id: '1' });
  const id: string = row.id;
  const page = await api.readListItem({ limit: 5 });
  const receipt = await api.commandChange({ id, ifMatch: '"0"', idempotencyKey: 'client-attempt-000001', body: {} });
  const ok: boolean = receipt.result.ok;
  return { id, ok, count: page.items.length, ApiError, describe };
}
`,
    );
    assert.deepEqual(await typecheck(client), { code: 0, out: '' });
    const checked = await typecheck(caller);
    assert.equal(checked.code, 0, checked.out);

    // Issued before serving, as the other App API suites do.
    const token = f.issue().token,
      readerToken = f.issue(['item:item', 'list:item']).token;
    const s = await serveApi(t, f);
    await s.started;
    const mod = (await import(`${client}?run=${Date.now()}`)) as Generated;
    const api = mod.createClient({ baseUrl: s.base, token });
    assert.deepEqual(await api.readItemItem({ id: '1' }), { id: '1', version: '0', name: 'One' });
    const page = await api.readListItem({ limit: 10 });
    assert.equal(page.items.length, 1);
    const applied = await api.commandChange({ id: '1', ifMatch: '"0"', idempotencyKey: 'client-attempt-000001', body: {} });
    assert.deepEqual(applied.result, { ok: true });
    assert.equal(applied.receipt.replayed, false);
    // The same version again is stale: a 409 problem the client types.
    await assert.rejects(
      api.commandChange({ id: '1', ifMatch: '"0"', idempotencyKey: 'client-attempt-000002', body: {} }),
      (error: unknown) => {
        assert.ok(error instanceof mod.ApiError);
        assert.equal(error.status, 409);
        assert.equal(error.problem?.code, 'stale_record');
        return true;
      },
    );
    // A token scoped to the reads is refused a command with a 403.
    const reader = mod.createClient({ baseUrl: s.base, token: () => readerToken });
    await assert.rejects(
      reader.commandChange({ id: '1', ifMatch: '"1"', idempotencyKey: 'client-attempt-000003', body: {} }),
      (error: unknown) => error instanceof mod.ApiError && error.status === 403,
    );
    s.child.kill('SIGTERM');
    assert.equal(await s.closed, 0);
  },
);
