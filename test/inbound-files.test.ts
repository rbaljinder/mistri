const SECRET = 'inbound-files-secret-value';
const MiB = 1024 * 1024;
const DATABASE = `inbound_files_${randomUUID().replaceAll('-', '')}`;
after(async () => {
  if (process.env.TABLEWALK_TEST_PG) await dropDedicatedPostgresDatabase(DATABASE);
});

const verifier = () =>
  hmac({
    secret: 'INBOUND_FILES_SECRET',
    signature: { header: 'x-signature', encoding: 'hex' },
    timestamp: { header: 'x-timestamp', window: '5 minutes' },
    signed: '{timestamp}.{body}',
  });
// `ref` records what the endpoint's input reader saw of the body: its keys, so a test can tell `files` never reached it.
const scanned = (files?: string) =>
  defineInbound({
    verify: verifier(),
    runAs: 'sender',
    command: 'scan',
    key: (body: { id: string }) => body.id,
    input: (body: Record<string, unknown>) => ({ ref: Object.keys(body).sort().join(',') }),
    ...(files === undefined ? {} : { files }),
  });

const scan = defineCommand({
  source: 'lab',
  target: 'scan',
  targets: 'none',
  input: { ref: field.text() },
  output: shape({ stored: number({ min: 0 }) }),
  async handle({ db, files }, input) {
    for (const file of files ?? []) await db.scan.insertFile(file, { ref: input.ref });
    return { stored: files?.length ?? 0 };
  },
});
// Writes a note and no file: an endpoint naming it with `files` would hand it bytes it has nowhere to keep.
const jot = defineCommand({
  source: 'lab',
  target: 'note',
  targets: 'none',
  input: { ref: field.text() },
  output: shape({ id: id() }),
  async handle({ db }, input) {
    return { id: Number((await db.note.insert({ ref: input.ref })).id) };
  },
});

const FILE = { content: 'data', name: 'file_name', type: 'content_type', size: 'byte_size' };
const SQLITE = `CREATE TABLE inb_scan (id INTEGER PRIMARY KEY, ref TEXT NOT NULL, file_name TEXT NOT NULL, content_type TEXT NOT NULL,
    byte_size INTEGER NOT NULL, data BLOB);
  CREATE TABLE inb_note (id INTEGER PRIMARY KEY, ref TEXT NOT NULL);`;
const POSTGRES = `CREATE TABLE public.inb_scan (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ref text NOT NULL,
    file_name text NOT NULL, content_type text NOT NULL, byte_size integer NOT NULL, data bytea);
  CREATE TABLE public.inb_note (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ref text NOT NULL);`;

interface Fixture {
  send: (path: string, payload: Record<string, unknown>) => Promise<Response>;
  rows: () => Promise<Array<{ ref: string; file_name: string; content_type: string; byte_size: number; data: Buffer }>>;
  prepare: (inbound: string) => ReturnType<typeof prepareJobs>;
  /** A request that says it weighs `length` and sends only `sent` of it, left open: what is answered, and the request. */
  partial: (
    path: string,
    length: number,
    headers: Record<string, string>,
    sent?: number,
  ) => { request: ClientRequest; reply: Promise<IncomingMessage> };
  /** Headers that look signed now (a fresh time, a digest of sha256's length), and verify nothing. */
  forged: () => Record<string, string>;
}

async function fixture(dialect: TenantDialect, run: (f: Fixture) => Promise<void>) {
  const engine = await openTenantEngine(dialect, {
    tables: ['inb_scan', 'inb_note'],
    sqlite: SQLITE,
    postgres: POSTGRES,
    database: DATABASE,
  });
  const registry = new Registry();
  process.env.INBOUND_FILES_SECRET = SECRET;
  let server: ReturnType<typeof createApp> | undefined;
  let store: IntegrationStore | undefined;
  const dir = mkdtempSync(join(tmpdir(), 'tw-inbound-files-'));
  try {
    await engine.migrateCommandJournal();
    if (dialect === 'sqlite') provisionSqliteIntegrations(engine.path);
    else await provisionPostgresIntegrations(engine.url);
    store = await openIntegrationStore(dialect === 'sqlite' ? { sqlite: engine.path } : { postgres: engine.url });
    const commands = defineCommands({ scan, jot });
    registry.add({ id: 'private-db', name: 'Lab', url: engine.path || engine.url, writable: true, source: 'config' });
    const app = parseAppConfig(
      {
        id: 'lab',
        name: 'Lab',
        sources: { lab: { connection: 'private-db' } },
        resources: {
          // 16 MiB: past the 256 KiB a delivery may otherwise weigh, and past the 10 MB default a file rule keeps.
          scan: { physical: engine.id('inb_scan'), access: 'write', file: { ...FILE, maxBytes: 16 * MiB } },
          note: { physical: engine.id('inb_note'), access: 'write' },
        },
        auth: { roles: { staff: { read: true }, integration: { read: true, service: true, commands: ['scan', 'jot'] } } },
        views: { scans: { kind: 'list', from: 'scan' } },
        home: 'scans',
      },
      'inbound files fixture',
    );
    const resources = await loadAppRuntimeResources(registry, app, 'private-db');
    const binding = bindBusinessCommands({ app, registry: commands, resources, writableConnection: () => true });
    const module = pinJobs(
      capturedJobModule(
        defineJobs({}, { principals: { sender: { roles: ['integration'] } }, inbound: { scans: scanned('scan'), plain: scanned() } }),
      ),
      commands,
    );
    const now = Date.parse('2026-11-13T12:00:00Z');
    const host = createInboundHost({
      endpoints: [...module.inbound.values()].map((endpoint) => inboundEndpoint(endpoint, process.env, inboundFileRule(app, endpoint))),
      appId: 'lab',
      principals: module.principals,
      bind: async () => ({ binding, release() {} }),
      deliveries: store,
      now: () => now,
      warn: () => {},
    });
    server = createApp({ registry, bound: { host: '127.0.0.1', port: 0 }, inbound: host });
    server.listen(0, '127.0.0.1');
    await new Promise((resolve) => server!.once('listening', resolve));
    const url = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
    const send: Fixture['send'] = (path, payload) => {
      const body = JSON.stringify(payload),
        timestamp = String(Math.floor(now / 1000));
      return fetch(`${url}/api/inbound/${path}`, {
        method: 'POST',
        body,
        headers: {
          'content-type': 'application/json',
          'x-timestamp': timestamp,
          'x-signature': createHmac('sha256', SECRET).update(`${timestamp}.${body}`).digest('hex'),
        },
      });
    };
    const rows: Fixture['rows'] = async () =>
      (await engine.all('SELECT ref, file_name, content_type, byte_size, data FROM inb_scan ORDER BY id')).map((row) => ({
        ref: String(row.ref),
        file_name: String(row.file_name),
        content_type: String(row.content_type),
        byte_size: Number(row.byte_size),
        data: Buffer.from(row.data as Uint8Array),
      }));
    const prepare: Fixture['prepare'] = (inbound) => {
      const file = join(dir, `jobs-${randomUUID()}.mjs`);
      writeFileSync(
        file,
        `import { defineInbound, defineJobs, hmac } from ${JSON.stringify(pathToFileURL(join(process.cwd(), 'packages/mistri/src/server/jobs.ts')).href)};
export default defineJobs({}, { principals: { sender: { roles: ['integration'] } }, inbound: { scans: defineInbound({
  verify: hmac({ secret: 'INBOUND_FILES_SECRET', signature: { header: 'x-signature' }, timestamp: { header: 'x-timestamp', window: '5 minutes' } }),
  runAs: 'sender', key: b => b.id, input: b => ({ ref: b.id }), ${inbound} }) } });
`,
      );
      return prepareJobs({ file, app, commands, resources, binding, locate: () => engine.path || engine.url });
    };
    const partial: Fixture['partial'] = (path, length, headers, sent = 1024) => {
      const sending = request(`${url}/api/inbound/${path}`, {
        method: 'POST',
        headers: { 'content-type': 'application/json', 'content-length': String(length), ...headers },
      });
      const reply = new Promise<IncomingMessage>((resolve, reject) => {
        sending.once('response', (answer: IncomingMessage) => resolve(answer.resume()));
        // A refusal closes the connection under a body still being sent: later errors are that, not the answer.
        sending.on('error', reject);
      });
      // One still holding its place when the test destroys it was answered nothing, and that is no failure.
      reply.catch(() => {});
      sending.write(Buffer.alloc(sent, 0x20));
      return { request: sending, reply };
    };
    const forged = () => ({ 'x-timestamp': String(Math.floor(now / 1000)), 'x-signature': 'ab'.repeat(32) });
    await run({ send, rows, prepare, partial, forged });
  } finally {
    await new Promise((resolve) => (server ? server.close(resolve) : resolve(undefined)));
    delete process.env.INBOUND_FILES_SECRET;
    await store?.close();
    await registry.closeAll();
    await engine.close();
    rmSync(dir, { recursive: true, force: true });
  }
}

test('defineInbound takes `files` as the name of one resource', () => {
  for (const files of ['', 'two words', 7, ['scan']])
    assert.throws(
      () => defineInbound({ verify: verifier(), runAs: 'sender', command: 'scan', key: () => 'k', input: () => ({}), files } as never),
      (error: Error) => error instanceof JobDeclarationError && /Inbound files names a file resource of the App/.test(error.message),
    );
  const captured = capturedJobModule(
    defineJobs({}, { principals: { sender: { roles: ['integration'] } }, inbound: { scans: scanned('scan') } }),
  );
  assert.equal(captured.inbound.get('scans')!.files, 'scan');
});

for (const { dialect, skip } of TENANT_DIALECTS)
  describe(`inbound files on ${dialect}`, { skip }, () => {
    test('a delivery of 12 MiB stores its file through the command, and the input reader never sees `files`', async () => {
      await fixture(dialect, async (f) => {
        const big = randomBytes(12 * MiB),
          small = Buffer.from('%PDF-1.7 a scan');
        const reply = await f.send('scans', {
          id: 'scan-1',
          files: [
            { name: 'reading.bin', type: 'application/octet-stream', content: big.toString('base64') },
            // A name is the sender's word for it, cleaned as an upload's is: a control character is no part of it.
            { name: 'report\u0007.PDF', type: 'Application/PDF', content: small.toString('base64') },
          ],
        });
        assert.equal(reply.status, 204, await reply.clone().text());
        const rows = await f.rows();
        assert.equal(rows.length, 2);
        assert.deepEqual(
          rows.map(({ ref, file_name, content_type, byte_size }) => ({ ref, file_name, content_type, byte_size })),
          [
            { ref: 'id', file_name: 'reading.bin', content_type: 'application/octet-stream', byte_size: 12 * MiB },
            { ref: 'id', file_name: 'report_.PDF', content_type: 'application/pdf', byte_size: small.length },
          ],
        );
        assert.ok(rows[0].data.equals(big), 'the bytes stored are the bytes sent');
        assert.ok(rows[1].data.equals(small));
      });
    });

    test('an endpoint without files keeps the 256 KiB cap, and keeps `files` as part of the body', async () => {
      await fixture(dialect, async (f) => {
        const heavy = await f.send('plain', { id: 'plain-1', note: 'x'.repeat(300 * 1024) });
        assert.equal(heavy.status, 413);
        const light = await f.send('plain', { id: 'plain-2', files: [] });
        assert.equal(light.status, 204, 'an endpoint that takes no files reads the body as it always did');
        assert.deepEqual(await f.rows(), []);
      });
    });

    test('a file past the cap is 413, a part that is not base64 or not a list is 400, and a replay answers the same', async () => {
      await fixture(dialect, async (f) => {
        const past = { id: 'scan-2', files: [{ name: 'huge.bin', content: Buffer.alloc(16 * MiB + 1).toString('base64') }] };
        assert.equal((await f.send('scans', past)).status, 413);
        assert.equal((await f.send('scans', past)).status, 413, 'the same delivery again: the same answer');
        assert.equal((await f.send('scans', { id: 'scan-3', files: [{ name: 'a.txt', content: 'not base64!' }] })).status, 400);
        assert.equal((await f.send('scans', { id: 'scan-4', files: { name: 'a.txt', content: '' } })).status, 400);
        assert.equal((await f.send('scans', { id: 'scan-5', files: ['a.txt'] })).status, 400);
        const many = Array.from({ length: 21 }, (_, n) => ({ name: `${n}.txt`, content: 'aGk=' }));
        assert.equal((await f.send('scans', { id: 'scan-6', files: many })).status, 400, 'at most twenty files at once');
        assert.deepEqual(await f.rows(), [], 'no refused delivery ran its command');
        const good = { id: 'scan-7', files: [{ name: 'a.txt', type: 'text/plain', content: 'aGk=' }] };
        assert.equal((await f.send('scans', good)).status, 204);
        assert.equal((await f.send('scans', good)).status, 204, "a replay answers the first delivery's receipt");
        assert.equal((await f.rows()).length, 1, 'and stores nothing twice');
      });
    });

    test('a large body is not read for a sender who could not have signed it, and only four are read at once', async () => {
      await fixture(dialect, async (f) => {
        const open: ClientRequest[] = [];
        try {
          // The answer arrives while 8 MiB of the said 8 MiB are still unsent: nothing was buffered to give it.
          const unsigned = f.partial('scans', 8 * MiB, {});
          open.push(unsigned.request);
          const refused = await unsigned.reply;
          assert.equal(refused.statusCode, 401);
          assert.equal(refused.headers.connection, 'close');
          const stale = f.partial('scans', 8 * MiB, {
            ...f.forged(),
            'x-timestamp': String(Math.floor(Date.parse('2026-11-13T11:00:00Z') / 1000)),
          });
          open.push(stale.request);
          assert.equal((await stale.reply).statusCode, 401, 'a signed time outside the window is refused unread too');
          const short = f.partial('scans', 8 * MiB, { ...f.forged(), 'x-signature': 'abcd' });
          open.push(short.request);
          assert.equal((await short.reply).statusCode, 401, "a digest that is not sha256's length is refused unread");
          const heavy = f.partial('scans', 64 * MiB, f.forged());
          open.push(heavy.request);
          assert.equal((await heavy.reply).statusCode, 413, 'a length past the cap is refused before it is read');
          // Four senders whose headers look signed hold the four places; the fifth is told to come back.
          const holding = Array.from({ length: 4 }, () => f.partial('scans', 8 * MiB, f.forged()));
          open.push(...holding.map((held) => held.request));
          await new Promise((resolve) => setTimeout(resolve, 200));
          const fifth = f.partial('scans', 8 * MiB, f.forged());
          open.push(fifth.request);
          const busy = await fifth.reply;
          assert.equal(busy.statusCode, 503);
          assert.equal(busy.headers['retry-after'], '5');
          // An endpoint without files keeps the 256 KiB cap and its order: no signature is asked for before it reads.
          assert.equal((await f.send('plain', { id: 'plain-3' })).status, 204);
        } finally {
          for (const held of open) held.destroy();
        }
        // Once they are gone, a signed delivery is read as ever; a forged one, read, still verifies nothing.
        await new Promise((resolve) => setTimeout(resolve, 200));
        assert.equal((await f.send('scans', { id: 'scan-8', files: [{ name: 'a.txt', content: 'aGk=' }] })).status, 204);
        const body = JSON.stringify({ id: 'scan-9' });
        const unread = f.partial('scans', Buffer.byteLength(body), f.forged(), 0);
        unread.request.end(body);
        assert.equal((await unread.reply).statusCode, 401);
        assert.equal((await f.rows()).length, 1);
      });
    });

    test('serving and check refuse files into a resource that holds none, or one the command does not write', async () => {
      await fixture(dialect, async (f) => {
        const prepared = await f.prepare(`command: 'scan', files: 'scan'`);
        assert.equal(prepared.module.inbound.get('scans')!.files, 'scan');
        await assert.rejects(
          f.prepare(`command: 'jot', files: 'note'`),
          /inbound endpoint "scans" takes files into "note", which is not a file resource of App "lab"/,
        );
        await assert.rejects(f.prepare(`command: 'scan', files: 'nowhere'`), /takes files into "nowhere", which is not a file resource/);
        await assert.rejects(
          f.prepare(`command: 'jot', files: 'scan'`),
          /inbound endpoint "scans" takes files into "scan", and command "jot" does not write it/,
        );
      });
    });
  });
