const read = (path) => readFileSync(join(ROOT, path), 'utf8');
const schemas = new Map();
const schemaFile = (name) => {
  if (!schemas.has(name)) schemas.set(name, JSON.parse(read(`packages/mistri/schema/${name}`)));
  return schemas.get(name);
};

/** A node with its `$ref`s followed; the nearest description and default win. */
function resolveNode(node, file, seen = []) {
  let description = node.description,
    def = node.default,
    type = node.type,
    enumValues = node.enum,
    name;
  let current = node,
    currentFile = file;
  while (current.$ref && !seen.includes(current.$ref)) {
    seen.push(current.$ref);
    const [other, pointer = ''] = current.$ref.split('#');
    currentFile = other || currentFile;
    let next = schemaFile(currentFile);
    for (const part of pointer.split('/').filter(Boolean)) next = next[part.replace(/~1/g, '/').replace(/~0/g, '~')];
    name ??= pointer.split('/').pop();
    description ??= next.description;
    def ??= next.default;
    type ??= next.type;
    enumValues ??= next.enum;
    current = next;
  }
  const branches = [...(current.oneOf ?? []), ...(current.anyOf ?? [])];
  const kinds = branches
    .map((branch) => resolveNode(branch, currentFile, [...seen]))
    .map((found) => found.type ?? found.name)
    .filter(Boolean);
  if (!type && kinds.length) type = [...new Set(kinds)].join(' | ');
  return { description, default: def, type: Array.isArray(type) ? type.join(' | ') : type, enum: enumValues, name };
}

/** Each authored source file of a sample App, in name order, with every property name it spells as one. */
function* spellings(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      // An App's own tests spell what they assert, not what the App declares.
      if (entry.name !== 'node_modules' && entry.name !== 'widgets' && entry.name !== 'tests') yield* spellings(path);
      continue;
    }
    if (!entry.name.endsWith('.ts') || /\.d\.ts$|\.test\./.test(entry.name)) continue;
    const source = readFileSync(path, 'utf8');
    const names = [...source.matchAll(/(?:^|[\s{,(])([A-Za-z_][A-Za-z0-9_]*)\??\s*:/g)].map((match) => match[1]);
    yield { path, names, dsl: /from\s+['"](?:tablewalk|@mistriwork\/mistri)\/app['"]/.test(source) };
  }
}

/** Every property name a sample App's source spells: test/coverage-map.test.ts asks whether Lintel still does. */
export function spelledIn(app) {
  const names = new Set();
  for (const file of spellings(join(ROOT, 'examples/apps', app))) for (const name of file.names) names.add(name);
  return names;
}

/** Where each property name is first spelled as one in a sample App. */
function usageIndex() {
  const index = new Map();
  for (const app of APPS) {
    const dir = join(ROOT, 'examples/apps', app);
    if (!existsSync(dir)) continue;
    for (const { path, names, dsl } of spellings(dir)) {
      const file = relative(join(ROOT, 'examples/apps'), path).replaceAll('\\', '/');
      for (const name of names) {
        const seen = index.get(name) ?? { first: undefined, files: new Set() };
        seen.files.add(file);
        /* Credited only to a module written in the App DSL: the jobs, commands, policy and workflow modules
           share key names (a decision's `inputs` and `where`, a workflow's `start`) with constructs they never
           declare, and crediting them sent a reader to the wrong file. They still count toward GENERIC. */
        if (dsl) seen.first ??= file;
        index.set(name, seen);
      }
    }
  }
  /* A name spelled in many files (label, title, query) says nothing about where to look. */
  return new Map([...index].filter(([, seen]) => seen.first && seen.files.size <= GENERIC).map(([name, seen]) => [name, seen.first]));
}

const cell = (text) =>
  String(text ?? '')
    .replace(/\s+/g, ' ')
    .replace(/\|/g, '\\|')
    .replace(/</g, '&lt;')
    .trim();
const lastKey = (path) => /([A-Za-z_][A-Za-z0-9_]*)(?:\[\])?$/.exec(path.replace(/\[[^\]]*\]$/, ''))?.[1];

/** The inventory's names for one schema file: `{ path: 'public' | 'preview' }`, without value rows. */
function inventoryPaths(prefix) {
  const dsl = readInventory().sections.dsl;
  const found = {},
    values = {},
    mirrors = {};
  for (const [name, status] of Object.entries(dsl)) {
    if (!name.startsWith(`${prefix}: `)) continue;
    const path = name.slice(prefix.length + 2);
    const mirror = /^(.*) mirrors (.*)$/.exec(path);
    const value = /^(.*) = (.*)$/.exec(path);
    if (mirror) mirrors[mirror[1]] = { of: mirror[2], status };
    else if (value) (values[value[1]] ??= []).push(value[2].replace(/^"|"$/g, ''));
    else found[path] = status;
  }
  return { found, values, mirrors };
}

/** A key a section list's kinds all share is one inventory entry, `sections[][kind=*].title`, not one per kind. */
const kindKey = (path) => /^(.*(?:sections|aside)\[\])\[kind=[^\]]+\](.*)$/.exec(path);

/** Every key of one schema file with its resolved node, from the same walk the inventory is made by. */
function describe(file, prefix) {
  const nodes = new Map();
  dslPaths(file, prefix, schemaFile, (path, node, from) => {
    if (!nodes.has(path)) nodes.set(path, resolveNode(node, from));
  });
  return nodes;
}

export function build() {
  const used = usageIndex();
  const inventories = { app: inventoryPaths('app'), page: inventoryPaths('page'), theme: inventoryPaths('theme') };
  const described = {
    app: describe('app.schema.json', ''),
    page: describe('page.schema.json', 'page'),
    theme: describe('theme.schema.json', 'theme'),
  };
  const problems = [];
  const pages = new Map();
  /* An entry for a key all the kinds share takes the node of the first kind that has it. */
  for (const [section, inventory] of Object.entries(inventories)) {
    for (const path of Object.keys(inventory.found)) {
      const star = /^(.*(?:sections|aside)\[\])\[kind=\*\](.*)$/.exec(path);
      if (!star || described[section].has(path)) continue;
      const first = [...described[section]].find(([other]) => {
        const match = kindKey(other);
        return match && match[1] === star[1] && match[2] === star[2];
      });
      if (first) described[section].set(path, first[1]);
    }
  }

  for (const [section, inventory] of Object.entries(inventories)) {
    for (const path of Object.keys(inventory.found)) {
      if (path.startsWith('$')) continue;
      if (!described[section].has(path))
        problems.push(`public name "${section}: ${path}" has no schema node, so there is nothing to print`);
    }
    for (const path of described[section].keys()) {
      if (path.startsWith('$') || path in inventory.found) continue;
      const shared = kindKey(path);
      if (shared && `${shared[1]}[kind=*]${shared[2]}` in inventory.found) continue;
      /* A key under a mirrored copy is listed once, at its original. */
      if (Object.keys(inventory.mirrors).some((copy) => path === copy || path.startsWith(`${copy}.`) || path.startsWith(`${copy}[`)))
        continue;
      problems.push(
        `schema key "${section}: ${path}" is not in test/fixtures/public-surface.json (run node scripts/public-surface.mjs --write)`,
      );
    }
  }
  if (problems.length) throw new Error(`DSL reference:\n  ${problems.slice(0, 25).join('\n  ')}`);

  for (const page of PAGES) {
    const rows = [];
    for (const section of ['app', ...(page.extra ?? [])]) {
      const inventory = inventories[section];
      const mine = (path) => section !== 'app' || page.keys.includes(path.split(/[.[]/)[0]);
      for (const [path, status] of Object.entries(inventory.found)) {
        if (path.startsWith('$') || !mine(path)) continue;
        rows.push({ section, path, status, node: described[section].get(path), values: inventory.values[path] });
      }
      for (const [path, { of, status }] of Object.entries(inventory.mirrors)) {
        if (!mine(path)) continue;
        rows.push({ section, path, status, mirror: of, values: undefined });
      }
    }
    rows.sort((a, b) => (a.section === b.section ? 0 : a.section === 'app' ? -1 : 1) || (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
    pages.set(page.slug, rows);
  }

  /** @type {Record<string, string>} */
  const files = {};
  for (const page of PAGES) {
    const rows = pages.get(page.slug);
    /* A section is a key and the keys under it, to three segments: the rest is a row of its table. */
    const groups = new Map();
    /* Two segments, unless that leaves a table too long to scan (resources.*). */
    const crowd = new Map();
    for (const row of rows) {
      const two = row.path.split('.').slice(0, 2).join('.');
      crowd.set(two, (crowd.get(two) ?? 0) + 1);
    }
    for (const row of rows) {
      const depth = crowd.get(row.path.split('.').slice(0, 2).join('.')) > 40 ? 3 : 2;
      const segments = row.path.split('.');
      const group = `${row.section === 'app' ? '' : `${row.section === 'page' ? 'page file' : 'theme file'}: `}${segments.slice(0, Math.min(segments.length, depth)).join('.')}`;
      if (!groups.has(group)) groups.set(group, []);
      groups.get(group).push(row);
    }
    const lines = [
      '---',
      `title: "${page.title}"`,
      `description: "${page.about}"`,
      '---',
      '',
      GENERATED,
      '',
      /* At 1.0 no key is preview; a later one makes its page say so. */
      rows.some((row) => row.status === 'preview')
        ? `${page.about} **Preview** keys work and may change in any release ([status](/docs/status/)); the rest are stable. [All parts](/docs/app-dsl/).`
        : `${page.about} Every key here is stable ([status](/docs/status/)). [All parts](/docs/app-dsl/).`,
      '',
      ...notes(page.slug),
    ];
    for (const [group, items] of groups) {
      lines.push(`## \`${group}\``, '', '| Key | Type | Status | What it does |', '| --- | --- | --- | --- |');
      for (const row of items) {
        if (row.mirror) {
          lines.push(
            `| \`${cell(row.path)}\` | | ${row.status === 'preview' ? 'Preview' : 'Stable'} | The same keys as \`${cell(row.mirror)}\`. |`,
          );
          continue;
        }
        const node = row.node;
        const key = lastKey(row.path);
        const sample = used.get(key);
        const type = node.enum
          ? node.enum.map((value) => `\`${cell(JSON.stringify(value))}\``).join(' · ')
          : cell(node.type ?? node.name ?? '');
        const values = row.values?.length ? ` One of ${row.values.map((value) => `\`${cell(value)}\``).join(', ')}.` : '';
        const dflt = node.default === undefined ? '' : ` Default \`${cell(JSON.stringify(node.default))}\`.`;
        const where = sample ? ` Used in \`examples/apps/${cell(sample)}\`.` : '';
        lines.push(
          `| \`${cell(row.path)}\` | ${type} | ${row.status === 'preview' ? 'Preview' : 'Stable'} | ${cell(node.description)}${values}${dflt}${where} |`,
        );
      }
      lines.push('');
    }
    files[`dsl-${page.slug}.md`] = lines.join('\n');
  }
  files['app-dsl.md'] = [
    '---',
    'title: "DSL reference"',
    'description: "Every key of an App definition, generated from its schema: one page per part of the App, each key with its type, status and use."',
    '---',
    '',
    GENERATED,
    '',
    ...notes('app-dsl'),
    '## The reference, by part',
    '',
    '| Part | What it holds |',
    '| --- | --- |',
    ...PAGES.map((page) => `| [${page.title.replace(/^App: /, '')}](/docs/dsl-${page.slug}/) | ${page.about} |`),
    '',
  ].join('\n');
  return files;
}

const GENERATED = `${MARK} from schema/, test/fixtures/public-surface.json and site/reference-notes/. Do not edit by hand. -->`;

/** A part's hand-written notes, set above its tables, or nothing. */
function notes(slug) {
  const path = join(NOTES, `${slug}.md`);
  return existsSync(path) ? [readFileSync(path, 'utf8').trim(), ''] : [];
}

function main() {
  const files = build();
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [name, text] of Object.entries(files)) {
    const path = join(OUT, name);
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== text) stale.push(name);
      continue;
    }
    writeFileSync(path, text);
  }
  for (const name of readdirSync(OUT))
    if (!(name in files) && owned(name)) {
      if (check) stale.push(name);
      else rmSync(join(OUT, name));
    }
  if (check && stale.length) {
    console.error(`The generated DSL reference is stale: ${stale.join(', ')}. Run node scripts/dsl-reference.mjs`);
    process.exit(1);
  }
  if (!check) console.log(`Wrote ${Object.keys(files).length} pages to ${relative(ROOT, OUT)}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
