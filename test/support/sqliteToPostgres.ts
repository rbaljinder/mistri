/**
 * A SQLite fixture copied onto PostgreSQL, for the sample Apps whose seeds only
 * speak SQLite: the tables with mapped types, their primary keys, NOT NULL,
 * simple defaults, unique and foreign keys, indexes, and every row. CHECK
 * constraints are left behind (they are the seed's guard, not the App's), and
 * the platform's own `__mistri_*` stores are not copied: PostgreSQL gets its
 * own, from the provisioners.
 *
 * Foreign keys are added after the rows, because a fixture may reference in a
 * circle (a department's lead is an employee, an employee has a department).
 */
import { DatabaseSync } from 'node:sqlite';
import type { PgQuery } from '../../packages/engine/src/adapters/postgresPool.js';

interface Column {
  name: string;
  type: string;
  notnull: number;
  dflt_value: string | null;
  pk: number;
}

const quote = (name: string) => `"${name.replaceAll('"', '""')}"`;

/** PostgreSQL's type for a declared SQLite one, by the same affinity rules SQLite reads it with, plus the names a fixture uses. */
function typeOf(declared: string): string {
  const type = declared.toUpperCase();
  if (type.includes('BOOL')) return 'boolean';
  if (type.includes('TIMESTAMP') || type.includes('DATETIME')) return 'timestamp';
  if (type === 'DATE') return 'date';
  if (type.includes('INT')) return 'integer';
  if (/REAL|FLOA|DOUB/.test(type)) return 'double precision';
  if (/NUMERIC|DECIMAL/.test(type)) return 'numeric';
  if (type.includes('BLOB')) return 'bytea';
  return 'text';
}

const bool = (value: unknown) => (value === null || value === undefined ? null : Number(value) !== 0);

export async function copySqliteToPostgres(file: string, pg: PgQuery): Promise<void> {
  const source = new DatabaseSync(file, { readOnly: true });
  try {
    const tables = (
      source
        .prepare(
          `SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\' AND name NOT LIKE '\\_\\_mistri%' ESCAPE '\\' ORDER BY rowid`,
        )
        .all() as Array<{ name: string }>
    ).map((row) => row.name);
    const columns = new Map<string, Column[]>();
    for (const table of tables) columns.set(table, source.prepare(`PRAGMA table_info(${quote(table)})`).all() as unknown as Column[]);
    const references: string[] = [];
    for (const table of tables) {
      const list = columns.get(table)!;
      const keys = list.filter((column) => column.pk > 0).sort((a, b) => a.pk - b.pk);
      const definitions = list.map((column) => {
        /* An integer key alone is SQLite's rowid alias; as an identity it takes the next id like one. */
        const identity = keys.length === 1 && keys[0] === column && /INT/i.test(column.type);
        /* A `version INTEGER NOT NULL` stays an integer, never null: the platform reads that shape as the record's revision. */
        const type = identity ? 'integer GENERATED BY DEFAULT AS IDENTITY' : typeOf(column.type);
        let fallback = '';
        if (column.dflt_value !== null && !identity) {
          const raw = column.dflt_value;
          if (/^CURRENT_TIMESTAMP$/i.test(raw)) fallback = ' DEFAULT CURRENT_TIMESTAMP';
          else if (typeOf(column.type) === 'boolean') fallback = ` DEFAULT ${Number(raw) !== 0}`;
          else if (/^-?\d+(\.\d+)?$/.test(raw) || /^'[^']*'$/.test(raw)) fallback = ` DEFAULT ${raw}`;
        }
        return `${quote(column.name)} ${type}${column.notnull || column.pk ? ' NOT NULL' : ''}${fallback}`;
      });
      if (keys.length) definitions.push(`PRIMARY KEY (${keys.map((column) => quote(column.name)).join(', ')})`);
      for (const index of source.prepare(`PRAGMA index_list(${quote(table)})`).all() as Array<{
        name: string;
        unique: number;
        origin: string;
      }>) {
        if (!index.unique || index.origin !== 'u') continue;
        const members = source.prepare(`PRAGMA index_info(${quote(index.name)})`).all() as Array<{ name: string }>;
        definitions.push(`UNIQUE (${members.map((member) => quote(member.name)).join(', ')})`);
      }
      await pg.query(`CREATE TABLE ${quote(table)} (${definitions.join(', ')})`);
      const groups = new Map<number, Array<{ from: string; table: string; to: string | null }>>();
      for (const link of source.prepare(`PRAGMA foreign_key_list(${quote(table)})`).all() as Array<{
        id: number;
        from: string;
        table: string;
        to: string | null;
      }>)
        groups.set(link.id, [...(groups.get(link.id) ?? []), link]);
      for (const group of groups.values()) {
        const to = group.every((link) => link.to)
          ? group.map((link) => quote(link.to!)).join(', ')
          : (columns.get(group[0]!.table) ?? [])
              .filter((column) => column.pk > 0)
              .map((column) => quote(column.name))
              .join(', ');
        references.push(
          `ALTER TABLE ${quote(table)} ADD FOREIGN KEY (${group.map((link) => quote(link.from)).join(', ')}) REFERENCES ${quote(group[0]!.table)} (${to})`,
        );
      }
    }
    for (const table of tables) {
      const list = columns.get(table)!;
      const names = list.map((column) => quote(column.name)).join(', ');
      const marks = list.map((_, index) => `$${index + 1}`).join(', ');
      for (const row of source.prepare(`SELECT ${names} FROM ${quote(table)}`).all() as Array<Record<string, unknown>>) {
        const values = list.map((column) => {
          const value = row[column.name];
          if (typeOf(column.type) === 'boolean') return bool(value);
          if (value instanceof Uint8Array) return Buffer.from(value);
          if (typeof value === 'bigint') return value.toString();
          return value;
        });
        await pg.query(`INSERT INTO ${quote(table)} (${names}) OVERRIDING SYSTEM VALUE VALUES (${marks})`, values);
      }
      const identity = list.filter((column) => column.pk > 0);
      if (identity.length === 1 && /INT/i.test(identity[0]!.type))
        await pg.query(
          `SELECT setval(pg_get_serial_sequence('${quote(table)}', '${identity[0]!.name}'), coalesce((SELECT max(${quote(identity[0]!.name)}) FROM ${quote(table)}), 0) + 1, false)`,
        );
    }
    for (const statement of references) await pg.query(statement);
    for (const row of source
      .prepare(`SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL AND tbl_name NOT LIKE '\\_\\_mistri%' ESCAPE '\\'`)
      .all() as Array<{ sql: string }>)
      await pg.query(row.sql);
  } finally {
    source.close();
  }
}
