test('CLI type export follows the app binding without opening an unrelated active connection', async () => {
  const dir = temp();
  try {
    const db = join(dir, 'fixture.db');
    database(db);
    const app = join(dir, 'app.ts');
    writeFileSync(
      app,
      'export default { name: "Bound Atlas", connection: "atlas", resources: { incidents: { physical: "physical_ticket" } }, views: { incidents: { kind: "list", from: "incidents" } }, home: "incidents" };',
    );
    const config = join(dir, 'config.json');
    writeFileSync(
      config,
      JSON.stringify({
        connections: [
          { name: 'unavailable', url: join(dir, 'missing.db') },
          { name: 'atlas', url: db },
        ],
        apps: [app],
      }),
    );
    const answer = await run(['--config', config, '--export', 'types']);
    assert.match(answer.stdout, /\n  incidents:/);
    assert.match(answer.stdout, /^export type Connections = "atlas" \| "unavailable";$/m);
    assert.doesNotMatch(answer.stderr, /Could not open the active/);
    writeFileSync(
      app,
      'export default { name: "Missing Atlas", connection: "missing", resources: { incidents: { physical: "physical_ticket" } }, views: { incidents: { kind: "list", from: "incidents" } }, home: "incidents" };',
    );
    await assert.rejects(run(['--config', config, '--export', 'types']), (error) => {
      const failure = error as Error & { stdout: string; stderr: string; code: number };
      assert.equal(failure.code, 1);
      assert.equal(failure.stdout, '');
      assert.match(failure.stderr, /names connection "missing", which is not configured/);
      return true;
    });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

