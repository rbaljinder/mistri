#!/usr/bin/env node
/**
 * The icon glyphs, written out as data: two weights of each for every page, two more for a theme that asks.
 *
 * The client drew its icons with `@phosphor-icons/react`, one import per
 * glyph. Each of those modules holds all six of Phosphor's weights — thin,
 * light, regular, bold, fill, duotone — and the tool draws two of them
 * (regular everywhere, bold for an App's logo). The other four were 14% of
 * every first page. This reads the package once, here, and keeps the
 * regular and bold path data of the glyphs the tool can draw:
 *
 *   packages/engine/src/shared/iconGlyphs.ts             every App icon (packages/engine/src/shared/appIcons.ts).
 *                                        The server sends an App the glyphs
 *                                        it names with its payload; the
 *                                        client never bundles the set.
 *   packages/kit/src/client/components/chromeIcons.ts the few the tool's own chrome draws
 *                                        (a caret, the menu, the gear), in
 *                                        the bundle because every App has them.
 *
 *   packages/engine/src/shared/iconWeights.ts            the light and fill drawing of each
 *                                        of both, for a theme that picks one
 *                                        (type.icons): a chunk of its own,
 *                                        fetched only then.
 *
 * All three are generated and committed; `test/icon-glyphs.test.ts` fails
 * when one no longer matches what this would write, so a new App icon or
 * a Phosphor upgrade is `node scripts/generate-icons.mjs` and a commit.
 *
 *   node scripts/generate-icons.mjs          write both files
 *   node scripts/generate-icons.mjs --check  say which is stale, write nothing
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(ROOT, 'package.json'));

/** What the tool's own chrome draws, whatever App is running. */
export const CHROME_ICONS = [
  'arrow-left',
  'caret-down',
  'caret-left',
  'caret-right',
  'calendar-blank',
  'bell',
  'check-circle',
  'gear',
  'list',
  'lock',
  'magnifying-glass',
  'star',
  'tray',
  'warning',
];

/** The App icon names, read from their one list without importing TypeScript. */
function appIconNames() {
  const source = readFileSync(join(ROOT, 'packages/engine/src/shared/appIcons.ts'), 'utf8');
  const list = /export const APP_ICONS = \[([\s\S]*?)\] as const;/.exec(source)?.[1];
  if (!list) throw new Error('packages/engine/src/shared/appIcons.ts no longer declares APP_ICONS as a literal list.');
  return [...list.replace(/\/\/.*$/gm, '').matchAll(/'([a-z-]+)'/g)].map((match) => match[1]);
}

const pascal = (name) =>
  name
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');

/** One glyph's path data in `weights` (`[regular, bold]` unless said), from the package's own definitions. */
async function glyph(name, weights = ['regular', 'bold']) {
  /* By path: the package's exports map sends a require of a definition to
     its whole CommonJS index. */
  const file = join(dirname(require.resolve('@phosphor-icons/react/package.json')), 'dist/defs', `${pascal(name)}.es.js`);
  const drawings = (await import(pathToFileURL(file).href)).default;
  return weights.map((weight) => {
    const drawing = drawings.get(weight);
    if (!drawing) throw new Error(`Phosphor has no ${weight} ${name}.`);
    const parts = [drawing.props.children].flat();
    return parts.map((part) => {
      /* Only bare paths are kept as data. A weight drawn any other way (a
         circle, an opacity) would be drawn wrong by a list of `d` strings,
         so it stops the generator rather than shipping a broken icon. */
      const extra = Object.keys(part.props).filter((key) => key !== 'd');
      if (part.type !== 'path' || extra.length) throw new Error(`${name} (${weight}) is not only paths: ${part.type} ${extra.join(' ')}.`);
      return part.props.d;
    });
  });
}

async function table(names, weights) {
  const rows = [];
  for (const name of names) rows.push(`  '${name}': ${JSON.stringify(await glyph(name, weights))},`);
  return rows.join('\n');
}

const HEADER = `/* Generated by scripts/generate-icons.mjs from @phosphor-icons/react
   (Phosphor Icons, MIT). Do not edit: change the script or the icon list and
   run it again. Each glyph is [regular, bold], each a list of SVG path data
   on Phosphor's 256-unit square. */`;

/** Both files' contents, by path from the repository root. */
export async function render() {
  const app = appIconNames();
  return {
    'packages/engine/src/shared/iconGlyphs.ts': `${HEADER}
import type { AppIconName } from './appIcons.js';

/** One glyph: its regular and its bold drawing. */
export type IconGlyph = readonly [regular: readonly string[], bold: readonly string[]];

export const APP_ICON_GLYPHS: Readonly<Record<AppIconName, IconGlyph>> = {
${await table(app)}
};
`,
    'packages/kit/src/client/components/chromeIcons.ts': `${HEADER}
import type { IconGlyph } from '@mistriwork/engine/shared/iconGlyphs.js';

export const CHROME_ICON_GLYPHS = {
${await table(CHROME_ICONS)}
} satisfies Record<string, IconGlyph>;
`,
    'packages/engine/src/shared/iconWeights.ts': `/* Generated by scripts/generate-icons.mjs from @phosphor-icons/react
   (Phosphor Icons, MIT). Do not edit: change the script or the icon list and
   run it again. Each glyph is [light, fill], each a list of SVG path data on
   Phosphor's 256-unit square: the two weights a theme may pick for its icons
   (type.icons) past the regular and bold every page has. A chunk of its own,
   fetched only when a worn theme picks one (client/iconWeight.ts). */

/** One glyph's light and fill drawings. */
export type IconWeightGlyph = readonly [light: readonly string[], fill: readonly string[]];

export const ICON_WEIGHT_GLYPHS: Readonly<Record<string, IconWeightGlyph>> = {
${await table([...new Set([...CHROME_ICONS, ...app])], ['light', 'fill'])}
};
`,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = await render();
  const stale = Object.entries(files).filter(([path, text]) => {
    try {
      return readFileSync(join(ROOT, path), 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (process.argv.includes('--check')) {
    for (const [path] of stale) console.error(`${path} is stale: run node scripts/generate-icons.mjs.`);
    process.exitCode = stale.length ? 1 : 0;
  } else {
    for (const [path, text] of stale) writeFileSync(join(ROOT, path), text);
    console.log(stale.length ? `Wrote ${stale.map(([path]) => path).join(', ')}.` : 'The icon glyphs are current.');
  }
}
