/**
 * `column: { in: { from, where } }` in a handler's, a loader's and a policy's `db.<table>.where` (commandDb.ts): the
 * column's value is the key of one of another table's rows, asked as `column IN (SELECT key FROM other WHERE …)`
 * where the read executes.
 *
 * The other table must be among the handle's reads, or the where is refused by name. A command's reads are the raw
 * adapter's, so the other table is read unscoped, as the table asked about is; a scoped read (a tenant's, a row
 * policy's, a loader's) plans the subquery through the same scope as a direct read of that table, so a row the reader
 * cannot see is never a key that matches. One level only. SQLite always; PostgreSQL when `TABLEWALK_TEST_PG` names a
 * disposable server (the schema `in_rows`, dropped before and after, so a mixed-case column is proved against the real
 * quoting and the subquery's values bind in order with the statement's).
 */
