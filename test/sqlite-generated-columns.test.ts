/*
 * A SQLite generated column is a column of its table: listed, read and
 * typed like any other, and never written. `PRAGMA table_info` leaves them
 * out, so they were invisible until the adapter read `table_xinfo`.
 */
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { test } from 'node:test';
import { SqliteAdapter } from '../packages/engine/src/adapters/sqlite.js';

test('generated columns are listed and read, marked unwritable, and refused by name on a write', async (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'tw-generated-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const file = join(directory, 'lines.db');
  const db = new DatabaseSync(file);
  db.exec(`CREATE TABLE line (
    id INTEGER PRIMARY KEY,
    quantity INTEGER NOT NULL,
    price REAL NOT NULL,
    total REAL GENERATED ALWAYS AS (quantity * price) VIRTUAL,
    label TEXT GENERATED ALWAYS AS ('x' || quantity) STORED
  );
  INSERT INTO line (quantity, price) VALUES (3, 2.5);`);
  db.close();

  const adapter = new SqliteAdapter(file, 'lines');
  t.after(() => adapter.close());
  const schema = await adapter.introspect();
  const columns = schema.tables.find((table) => table.name === 'line')!.columns;
  assert.deepEqual(
    columns.map((column) => [column.name, column.type, column.writable]),
    [
      ['id', 'INTEGER', undefined],
      ['quantity', 'INTEGER', undefined],
      ['price', 'REAL', undefined],
      ['total', 'REAL', false],
      ['label', 'TEXT', false],
    ],
  );

  const read = await adapter.query({ table: 'line', columns: ['id', 'total', 'label'], limit: 10, offset: 0 });
  assert.deepEqual(read.rows, [{ id: 1, total: 7.5, label: 'x3' }]);

  // The database computes them: a write naming one is refused in words, not the engine's.
  await assert.rejects(
    adapter.insert({ table: 'line', values: { quantity: 1, price: 1, total: 9 } }),
    /"total" is generated by the database/,
  );
  await assert.rejects(adapter.update({ table: 'line', key: { id: 1 }, values: { label: 'y' } }), /"label" is generated by the database/);
  const inserted = await adapter.insert({ table: 'line', values: { quantity: 2, price: 4 } });
  assert.equal(inserted.row?.total, 8);
});
