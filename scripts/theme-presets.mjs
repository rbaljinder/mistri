#!/usr/bin/env node
/**
 * The built-in looks, written out as the definitions the browser wears.
 *
 * The looks are specs (packages/engine/src/shared/themeLooks.ts), built by the same
 * `buildTheme` an App's own theme goes through. Building them in the browser
 * put the builder — the colour derivations, the role map — in every App's
 * first paint, to compute the same three definitions on every visit; their
 * built form is smaller in brotli than the specs and the builder together.
 * So they are built here, once, into packages/engine/src/shared/builtInThemes.ts, and
 * `test/theme-spec.test.ts` fails when that file no longer matches what this
 * would write: a change to a look is this script and a commit.
 *
 *   node --import tsx scripts/theme-presets.mjs          write the file
 *   node --import tsx scripts/theme-presets.mjs --check  say whether it is stale, write nothing
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PRESETS_FILE = 'packages/engine/src/shared/builtInThemes.ts';

/** The roles a palette may set, in the order a packed palette lists them. */
const ROLES = [
  'ground',
  'surface',
  'raised',
  'line',
  'lineStrong',
  'lineControl',
  'ink',
  'inkMuted',
  'inkSubtle',
  'accent',
  'accentSoft',
  'link',
  'focus',
  'onAccent',
  'accentInk',
  'statusGood',
  'statusWarning',
  'statusCritical',
  'statusInfo',
  'navGround',
  'navInk',
  'navMuted',
  'navLine',
  'navAccent',
  'navCurrent',
  'navOnCurrent',
  'chart1',
  'chart2',
  'chart3',
  'chart4',
  'chart5',
  'chart6',
  'chart7',
  'chart8',
  'rulesSection',
  'rulesHead',
  'rulesWeight',
  'rulesControl',
  /* Last, so a palette that leaves a form's primary action to its accent packs no "-" for it. */
  'primary',
  'onPrimary',
  /* Roles only a look with a paper of its own says (Workshop's): last, so the others pack none of them. */
  'shadow',
  'band',
  'field',
];

/* A palette written as its values in ROLES order, one space apart, "-" where it sets none. Spelled out, the
   role names were more than half of the file, and the file is in every App's first paint: the same names,
   about 34 times over. */
function pack(palette) {
  const extra = Object.keys(palette).filter((role) => !ROLES.includes(role));
  if (extra.length) throw new Error(`A palette sets ${extra.join(', ')}, which ROLES in scripts/theme-presets.mjs does not list.`);
  for (const value of Object.values(palette))
    if (typeof value !== 'string' || /[\s]/.test(value) || value === '-')
      throw new Error(`A palette value ${JSON.stringify(value)} cannot be packed.`);
  return `p(${JSON.stringify(
    ROLES.map((role) => palette[role] ?? '-')
      .join(' ')
      .replace(/( -)+$/, ''),
  )})`;
}

/* The roles worn with the accent: a palette that moves the accent says them even where they match the look's own, since
   a palette laid over a look drops the inks and the ring it does not say (themePresets.ts overlayPalette). */
const WITH_ACCENT = ['accent', 'onAccent', 'accentInk', 'focus'];

/* A palette as what it changes from the look's own colors: every look wears all of them (lookPalettes.ts), and the
   built file is in every App's first paint, so a role the palette leaves as the look has it is not written twice. */
export function changes(variant, base) {
  const moves = variant.accent !== base.accent;
  return Object.fromEntries(
    Object.entries(variant).filter(([role, value]) => value !== base[role] || (moves && WITH_ACCENT.includes(role))),
  );
}

/** The file's text: the looks built, as data. */
export async function render() {
  const { LOOKS } = await import('../packages/engine/src/shared/themeLooks.ts');
  const { buildTheme } = await import('../packages/mistri/src/shared/themeBuild.ts');
  const presets = LOOKS.map((look) => ({ ...buildTheme(look), base: look.id }));
  const packed = [];
  const mark = (palette) => (palette ? `\u0000${packed.push(pack(palette)) - 1}` : palette);
  const marked = presets.map((preset) => ({
    ...preset,
    light: mark(preset.light),
    dark: mark(preset.dark),
    ...(preset.palettes
      ? {
          palettes: preset.palettes.map((variant) => ({
            ...variant,
            light: mark(changes(variant.light, preset.light)),
            dark: mark(changes(variant.dark, preset.dark)),
          })),
        }
      : {}),
  }));
  const data = JSON.stringify(marked, null, 2).replace(/"\\u0000(\d+)"/g, (_, index) => packed[Number(index)]);
  return `/* Generated by scripts/theme-presets.mjs from packages/engine/src/shared/themeLooks.ts: do not edit.
   Change a look there and run \`node --import tsx scripts/theme-presets.mjs\`. */
import type { ThemeDefinition, ThemePalette } from '../../schema/theme.js';

const ROLES = ${JSON.stringify(ROLES)} as const;

/** A palette from its values in ROLES order ("-" for a role it leaves to its base). */
function p(values: string): ThemePalette {
  const palette: Record<string, string> = {};
  values.split(' ').forEach((value, index) => {
    if (value !== '-') palette[ROLES[index]!] = value;
  });
  return palette as unknown as ThemePalette;
}

export const THEME_PRESETS: readonly ThemeDefinition[] = ${data};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await render();
  let current = '';
  try {
    current = readFileSync(join(ROOT, PRESETS_FILE), 'utf8');
  } catch {
    /* not written yet */
  }
  if (process.argv.includes('--check')) {
    if (current !== text) console.error(`${PRESETS_FILE} is stale: run node --import tsx scripts/theme-presets.mjs.`);
    process.exitCode = current === text ? 0 : 1;
  } else if (current !== text) {
    writeFileSync(join(ROOT, PRESETS_FILE), text);
    console.log(`Wrote ${PRESETS_FILE}.`);
  } else console.log('The built-in looks are current.');
}
