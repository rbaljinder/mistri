/**
 * Proposals over the App's own command door on PostgreSQL: the scenario in support/proposalsOverHttp.ts, with the
 * journal in its own schema and two approvals racing on a real server. Live and opt-in like postgres.test.ts
 * (`TABLEWALK_TEST_PG`, and `TABLEWALK_REQUIRE_LIVE=1` to fail rather than skip). It drops and recreates its own
 * tables in `public` of the database it is pointed at.
 */
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import type { PgQuery } from '../packages/engine/src/adapters/postgresPool.js';
import { runtimeTable } from '../packages/engine/src/shared/runtimeTables.js';
import { migratePostgresCommandJournal } from '../packages/mistri/src/adapters/commands/postgresCommandJournal.js';
import { liveSkip } from './live.js';
import { proposalsOverHttp } from './support/proposalsOverHttp.js';

const LIVE = process.env.TABLEWALK_TEST_PG;

interface Control extends PgQuery {
  connect(): Promise<void>;
  end(): Promise<void>;
}
async function client(): Promise<Control> {
  const specifier = 'pg';
  const pg = (await import(specifier)) as { default?: { Client: new (c: unknown) => Control }; Client?: new (c: unknown) => Control };
  const Client = (pg.Client ?? pg.default?.Client)!;
  const created = new Client({ connectionString: LIVE });
  await created.connect();
  return created;
}

const RESET = [`DROP TABLE IF EXISTS public.assignment, public.loan CASCADE`, `DROP SCHEMA IF EXISTS mistri CASCADE`];
const SETUP = [
  `CREATE TABLE public.loan (id integer PRIMARY KEY, title text NOT NULL, version integer NOT NULL DEFAULT 0)`,
  `CREATE TABLE public.assignment (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     loan_id integer NOT NULL REFERENCES public.loan (id), reviewer text NOT NULL)`,
  `INSERT INTO public.loan VALUES (1, 'Corner shop', 0), (2, 'Bakery', 0)`,
];

test(
  'on PostgreSQL, a proposal is approved as its approver, refused without the grant, decided once, failed, dismissed and gone',
  { timeout: 60_000, skip: liveSkip('postgres', LIVE) },
  async () => {
    const control = await client();
    const directory = mkdtempSync(join(tmpdir(), 'mistri-command-proposals-http-pg-'));
    try {
      for (const statement of [...RESET, ...SETUP]) await control.query(statement);
      await migratePostgresCommandJournal(LIVE!);
      await proposalsOverHttp({
        url: LIVE!,
        directory,
        table: (name) => runtimeTable('postgres', name),
        all: async (sql, params = []) => {
          let n = 0;
          return (
            await control.query(
              sql.replace(/\?/g, () => `$${++n}`),
              [...params],
            )
          ).rows;
        },
      });
    } finally {
      for (const statement of RESET) await control.query(statement).catch(() => {});
      await control.end();
      rmSync(directory, { recursive: true, force: true });
    }
  },
);
