const LIVE = process.env.TABLEWALK_TEST_PG;
const SCHEMA = 'in_rows';

type Row = Record<string, unknown>;
interface World {
  /** A local table name as this database ids it (schema-qualified on PostgreSQL). */
  id(table: string): string;
  readonly adapter: SqliteAdapter | PostgresAdapter;
  schema(): Promise<DatabaseSchema>;
  close(): Promise<void>;
}

/* Four customers in two tenants: 1 (t1, west, gold), 2 (t1, east, basic), 3 (t2, west, gold), 4 (t1, west, basic).
   Six invoices: 1 (t1, customer 1, 50), 2 (t1, 2, 5), 3 (t2, 3, 70), 4 (t1, 4, 90), 5 (t1, 1, 10), and 6, a tenant-2
   invoice pointing at tenant 1's customer 1 (30), so a tenant's subquery is seen to drop another tenant's key.
   A contact has a two-column key; a note is never declared. "Tier" is mixed case. */
function statements(postgres: boolean): string[] {
  const pk = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  return [
    `CREATE TABLE customer (id ${pk}, tenant_id INTEGER NOT NULL, region TEXT NOT NULL, "Tier" TEXT NOT NULL)`,
    `CREATE TABLE invoice (id ${pk}, tenant_id INTEGER NOT NULL, customer_id INTEGER NOT NULL REFERENCES customer (id), total INTEGER NOT NULL)`,
    `CREATE TABLE contact (region TEXT NOT NULL, num INTEGER NOT NULL, PRIMARY KEY (region, num))`,
    `CREATE TABLE note (id ${pk}, body TEXT)`,
    `INSERT INTO customer VALUES (1, 1, 'west', 'gold'), (2, 1, 'east', 'basic'), (3, 2, 'west', 'gold'), (4, 1, 'west', 'basic')`,
    `INSERT INTO invoice VALUES (1, 1, 1, 50), (2, 1, 2, 5), (3, 2, 3, 70), (4, 1, 4, 90), (5, 1, 1, 10), (6, 2, 1, 30)`,
    `INSERT INTO contact VALUES ('west', 1)`,
    `INSERT INTO note VALUES (1, 'x')`,
  ];
}

async function sqliteWorld(): Promise<World> {
  const directory = mkdtempSync(join(tmpdir(), 'mistri-in-'));
  const file = join(directory, 'data.db');
  const db = new DatabaseSync(file);
  for (const statement of statements(false)) db.exec(statement);
  const adapter = new SqliteAdapter(file, 'in');
  return {
    id: (table) => table,
    adapter,
    schema: () => adapter.introspect(),
    async close() {
      await adapter.close();
      db.close();
      rmSync(directory, { recursive: true, force: true });
    },
  };
}

async function postgresWorld(): Promise<World> {
  const specifier = 'pg';
  const pg = (await import(specifier)) as { default?: { Client: never }; Client?: never };
  const Client = (pg.Client ?? pg.default?.Client)! as new (c: unknown) => {
    connect(): Promise<void>;
    query(sql: string, params?: readonly unknown[]): Promise<{ rows: Row[] }>;
    end(): Promise<void>;
  };
  const control = new Client({ connectionString: LIVE, statement_timeout: 60_000 });
  await control.connect();
  await control.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE; CREATE SCHEMA ${SCHEMA}`);
  await control.query(`SET search_path TO ${SCHEMA}`);
  for (const statement of statements(true)) await control.query(statement);
  const adapter = new PostgresAdapter(LIVE!, 'in', [SCHEMA]);
  return {
    id: (table) => `${SCHEMA}.${table}`,
    adapter,
    schema: () => adapter.introspect(),
    async close() {
      await adapter.close();
      await control.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await control.end();
    },
  };
}

const ids = (rows: readonly Row[]) => rows.map((row) => Number(row.id)).sort((a, b) => a - b);
const DECLARED = ['invoice', 'customer', 'contact'];
const west = { customer_id: { in: { from: 'customer', where: { region: 'west' } } } };

type Handle = {
  where(where: object): PromiseLike<Row[]> & { first(): Promise<Row | undefined> };
  find(where: object): Promise<Row | undefined>;
  count(where: object): Promise<number>;
};
type WriteHandle = Handle & {
  updateWhere(where: object, changes: Row): Promise<Row[]>;
  update(row: Row, changes: Row): Promise<Row>;
};

function proofs(open: () => Promise<World>, label: string, skip: false | string = false) {
  describe(`in-subqueries in a handler's db on ${label}`, { skip }, () => {
    let w: World;
    before(async () => {
      w = await open();
    });
    after(async () => {
      await w?.close();
    });

    /** A handle set over the raw adapter, as a command's (and a policy's) is: local names mapped to the database's. */
    const handles = async (reads: readonly string[], grant?: (schema: DatabaseSchema) => Parameters<typeof authorizeColumnWrites>[1]) => {
      const schema = await w.schema();
      const catalog = commandCatalog(schema, reads, (local) => w.id(local));
      assert.ok(catalog, 'the catalog builds');
      const physical = (local: string) => w.id(local);
      /* A command's transaction is held to its grant's columns (columnGrants.ts) when the App names a grant. */
      const below = grant
        ? authorizeColumnWrites(schema, grant(schema), {
            query: (request: never) => w.adapter.query(request),
            count: (table: string, filter?: never) => w.adapter.count(table, filter),
          } as never)
        : w.adapter;
      const tx = {
        query: (request: { table: string; filter?: never }) =>
          below.query({ ...request, table: physical(request.table), filter: renamedAnyRows(request.filter, physical) } as never),
        count: (table: string, filter?: never) => below.count(physical(table), renamedAnyRows(filter, physical)),
      };
      return createCommandDb({ tx: tx as never, catalog, read: reads, write: [], now: () => new Date() }) as unknown as Record<
        string,
        Handle
      >;
    };
    const invoices = async (where: object, reads: readonly string[] = DECLARED) => ids(await (await handles(reads)).invoice.where(where));

    test("a command reads the invoices whose customer is among the other table's matching rows", async () => {
      assert.deepEqual(await invoices(west), [1, 3, 4, 5, 6]);
      assert.deepEqual(
        await invoices({ customer_id: { in: { from: 'customer', where: { region: 'west', Tier: 'gold' } } } }),
        [1, 3, 5, 6],
      );
      // The other table's where is the object form's own: a list, an operator, and nothing at all.
      assert.deepEqual(await invoices({ customer_id: { in: { from: 'customer', where: { region: ['east'] } } } }), [2]);
      assert.deepEqual(await invoices({ customer_id: { in: { from: 'customer', where: { region: { not: 'west' } } } } }), [2]);
      assert.deepEqual(await invoices({ customer_id: { in: { from: 'customer', where: {} } } }), [1, 2, 3, 4, 5, 6]);
      const db = await handles(DECLARED);
      assert.equal(await db.invoice.count(west), 5);
      assert.equal((await db.invoice.find({ customer_id: { in: { from: 'customer', where: { region: 'east' } } } }))?.id, 2);
      assert.equal((await db.invoice.where(west).first())?.id !== undefined, true);
    });

    test('values beside and inside the test bind in the order they are written', async () => {
      // total > $1, then the subquery's region = $2 and "Tier" = $3, then total < $4: a misnumbered placeholder reads another value.
      assert.deepEqual(
        await invoices({ total: { gt: 20 }, customer_id: { in: { from: 'customer', where: { region: 'west', Tier: 'gold' } } } }),
        [1, 3, 6],
      );
      assert.deepEqual(
        await invoices({ customer_id: { in: { from: 'customer', where: { Tier: 'gold' } } }, total: { lt: 60 }, tenant_id: 1 }),
        [1, 5],
      );
      // Two tests on one where: each its own subquery.
      assert.deepEqual(
        await invoices({
          customer_id: { in: { from: 'customer', where: { region: 'west' } } },
          id: { in: { from: 'invoice', where: { total: { gte: 30 } } } },
        }),
        [1, 3, 4, 6],
      );
    });

    test('a where that matches no row of the other table matches nothing, and nothing is read', async () => {
      assert.deepEqual(await invoices({ customer_id: { in: { from: 'customer', where: { region: [] } } } }), []);
      assert.equal(await (await handles(DECLARED)).invoice.count({ customer_id: { in: { from: 'customer', where: { region: [] } } } }), 0);
      assert.deepEqual(await invoices({ customer_id: { in: { from: 'customer', where: { region: 'north' } } } }), []);
    });

    test('a table outside the declared reads is refused by name', async () => {
      const db = await handles(['invoice']);
      await assert.rejects(
        async () => db.invoice.where(west),
        /invoice: "customer_id: \{ in: \{ from: 'customer' \} \}" reads customer, which is not among the tables this handle reads \(invoice\); declare it in read or write\./,
      );
      await assert.rejects(
        async () => db.invoice.count({ customer_id: { in: { from: 'note', where: {} } } }),
        /reads note, which is not among/,
      );
    });

    test('a nested test, a malformed one, a column either side lacks and a key of two columns are refused by name', async () => {
      const db = await handles(DECLARED);
      await assert.rejects(
        async () => db.invoice.where({ customer_id: { in: { from: 'customer', where: { id: { in: { from: 'invoice', where: {} } } } } } }),
        /invoice: "customer_id: \{ in: … \}" reads one level; "id: \{ in: … \}" inside it is refused, so read customer's rows first\./,
      );
      for (const bad of [
        { in: 'customer' },
        { in: { from: 'customer', where: {}, limit: 1 } },
        { in: { from: 'customer', where: {} }, gt: 1 },
        { in: { table: 'customer' } },
      ])
        await assert.rejects(
          async () => db.invoice.where({ customer_id: bad }),
          /invoice: "customer_id: \{ in: … \}" is written \{ in: \{ from: 'table', where: \{ … \} \} \} and stands alone\./,
        );
      await assert.rejects(
        async () => db.invoice.where({ customer_id: { in: { from: 'customer', where: 'region = west' } } }),
        /judges customer's rows by an object where/,
      );
      await assert.rejects(
        async () => db.invoice.where({ nope: { in: { from: 'customer', where: {} } } }),
        /"nope" is not one of its columns/,
      );
      await assert.rejects(
        async () => db.invoice.where({ customer_id: { in: { from: 'customer', where: { nope: 1 } } } }),
        /customer: "nope" is not one of its columns/,
      );
      await assert.rejects(
        async () => db.invoice.where({ customer_id: { in: { from: 'contact', where: {} } } }),
        /selects contact's key, and contact has no key of exactly one column/,
      );
    });

    test("a where compiled outside a handle's db (a lookup, a when) refuses the test by name", async () => {
      const catalog = commandCatalog(await w.schema(), DECLARED, (local) => w.id(local))!;
      assert.throws(
        () => compileWhere(catalog.invoice!, west, new Date()),
        /invoice: "customer_id: \{ in: … \}" reads another table's rows, which only a handler's db reads\./,
      );
      const compiled = compileWhere(catalog.invoice!, west, new Date(), [], undefined, { anyRows: true });
      assert.deepEqual(compiled.filter.groups, [
        [
          {
            column: 'customer_id',
            op: 'in',
            within: { table: 'customer', filter: { groups: [[{ column: 'region', op: '=', value: 'west' }]] } },
          },
        ],
      ]);
    });

    test('a command held to its grant reads the test, and a table, key or column outside the grant is refused', async () => {
      const id = (table: string) => w.id(table);
      const grant = (readable: readonly string[], customer: readonly string[]) => () => ({
        readable: new Set(readable.map(id)),
        writable: new Set<string>(),
        fields: new Map([[id('customer'), { read: new Set(customer), write: new Set<string>() }]]),
      });
      const granted = await handles(DECLARED, grant(DECLARED, ['id', 'region']));
      assert.deepEqual(ids(await granted.invoice.where(west)), [1, 3, 4, 5, 6]);
      const denied = (error: Error) => error.name === 'AppAccessDenied';
      // "Tier" is not among the columns this grant reads on customer.
      await assert.rejects(
        async () => granted.invoice.where({ customer_id: { in: { from: 'customer', where: { Tier: 'gold' } } } }),
        denied,
      );
      // The key the subquery selects must be readable too.
      const keyless = await handles(DECLARED, grant(DECLARED, ['region']));
      await assert.rejects(async () => keyless.invoice.count(west), denied);
      // A table the grant does not read at all.
      const narrower = await handles(DECLARED, grant(['invoice', 'contact'], ['id', 'region']));
      await assert.rejects(async () => narrower.invoice.where(west), denied);
    });

    test('the raw adapter refuses an unknown table, an unknown column and a second level, never drops them', async () => {
      const read = (condition: Condition) =>
        w.adapter.query({ table: w.id('invoice'), limit: 10, offset: 0, filter: { groups: [[condition]] } });
      const within = (table: string, filter?: Condition[][]): Condition => ({
        column: 'customer_id',
        op: 'in',
        within: { table: w.id(table), ...(filter ? { filter: { groups: filter } } : {}) },
      });
      await assert.rejects(read(within('ghost')), /Unknown table in an "in" test/);
      await assert.rejects(read(within('customer', [[{ column: 'nope', op: '=', value: 1 }]])), /Unknown column in an "in" test/);
      await assert.rejects(read(within('customer', [[within('invoice')]])), /An "in" test reads one level/);
      await assert.rejects(read(within('contact')), /contact has no key of exactly one column/);
      await assert.rejects(read({ ...within('customer'), op: '=' }), /cannot compare a column with another table's rows/);
    });

    /** A handle set that writes invoices inside one of the adapter's transactions, as a command's does. */
    const writing = <T>(run: (db: Record<string, WriteHandle>) => Promise<T>) =>
      w.adapter.transaction(async (raw) => {
        const catalog = commandCatalog(await w.schema(), DECLARED, (local) => w.id(local))!;
        const physical = (local: string) => w.id(local);
        const named = (request: UpdateRequest) => ({ ...request, table: physical(request.table) });
        const tx = {
          query: (request: QueryRequest) =>
            raw.query({ ...request, table: physical(request.table), filter: renamedAnyRows(request.filter, physical) }),
          count: (table: string, filter?: Filter) => raw.count(physical(table), renamedAnyRows(filter, physical)),
          update: (request: UpdateRequest) => raw.update(named(request)),
          ...(raw.updateMany ? { updateMany: (requests: readonly UpdateRequest[]) => raw.updateMany!(requests.map(named)) } : {}),
        };
        return run(createCommandDb({ tx: tx as never, catalog, read: DECLARED, write: ['invoice'], now: () => new Date() }) as never);
      });
    const totals = async (): Promise<Record<number, number>> =>
      Object.fromEntries(
        (await w.adapter.query({ table: w.id('invoice'), limit: 100, offset: 0 })).rows.map((row) => [Number(row.id), Number(row.total)]),
      );

    test("updateWhere writes only the rows whose key the other table's where selects, and leaves the rest as they were", async () => {
      const before = await totals();
      // A copy: asserted itself, `before` would narrow to these six keys and could not be indexed by a row.
      assert.deepEqual({ ...before }, { 1: 50, 2: 5, 3: 70, 4: 90, 5: 10, 6: 30 });
      try {
        /* West and gold is customers 1 and 3: invoices 1, 3, 5 and 6. Customer 4 is west but basic, so invoice 4 is
           read by the plain west test above and must not be written here; invoice 2's customer is east. */
        const written = await writing((db) =>
          db.invoice!.updateWhere({ customer_id: { in: { from: 'customer', where: { region: 'west', Tier: 'gold' } } } }, { total: 0 }),
        );
        assert.deepEqual(ids(written), [1, 3, 5, 6]);
        assert.ok(written.every((row) => Number(row.total) === 0));
        assert.deepEqual(await totals(), { ...before, 1: 0, 3: 0, 5: 0, 6: 0 });
        // Beside a plain test of the invoice's own, and binding after it: tenant 1's west invoices only.
        const narrower = await writing((db) =>
          db.invoice!.updateWhere({ tenant_id: 1, customer_id: { in: { from: 'customer', where: { region: 'west' } } } }, { total: 7 }),
        );
        assert.deepEqual(ids(narrower), [1, 4, 5]);
        assert.deepEqual(await totals(), { ...before, 1: 7, 3: 0, 4: 7, 5: 7, 6: 0 });
        // A subquery that selects no key writes nothing.
        const none = await writing((db) =>
          db.invoice!.updateWhere({ customer_id: { in: { from: 'customer', where: { region: 'north' } } } }, { total: 1 }),
        );
        assert.deepEqual(none, []);
        assert.deepEqual(await totals(), { ...before, 1: 7, 3: 0, 4: 7, 5: 7, 6: 0 });
      } finally {
        // The later tests read these totals: each row back as it was.
        await writing(async (db) => {
          for (const row of await db.invoice!.where({})) await db.invoice!.update(row, { total: before[Number(row.id)] });
        });
      }
      assert.deepEqual(await totals(), before);
    });
  });

  describe(`in-subqueries under a scope on ${label}: the other table is read as a direct read of it would be`, { skip }, () => {
    let w: World;
    before(async () => {
      w = await open();
    });
    after(async () => {
      await w?.close();
    });

    const tenant = (n: number, invoice: boolean): RowScope => ({
      [w.id('invoice')]: invoice ? { groups: [[{ column: 'tenant_id', op: '=', value: n } as Condition]] } : true,
      [w.id('customer')]: { groups: [[{ column: 'tenant_id', op: '=', value: n } as Condition]] },
      [w.id('contact')]: true,
      [w.id('note')]: true,
    });
    const inWest = (filter: Condition[] = []): Filter => ({
      groups: [
        [
          ...filter,
          {
            column: 'customer_id',
            op: 'in',
            within: { table: w.id('customer'), filter: { groups: [[{ column: 'region', op: '=', value: 'west' }]] } },
          },
        ],
      ],
    });

    test("a tenant's subquery never matches another tenant's rows, in a scoped transaction's reads", async () => {
      const read = (scope: RowScope, filter: Filter) =>
        w.adapter.scopeTransaction(scope, async (tx) =>
          ids((await tx.query({ table: w.id('invoice'), limit: 100, offset: 0, filter })).rows),
        );
      // Unscoped, the west customers are 1, 3 and 4. Tenant 1 sees 1 and 4, so invoice 3 (tenant 2's customer 3) is dropped
      // even though the invoice table is read whole here: the subquery carries the customer's scope, not the invoice's.
      assert.deepEqual(await read(tenant(1, false), inWest()), [1, 4, 5, 6]);
      // Tenant 2 reads its own invoices, 3 and 6; 6 points at tenant 1's customer 1, which is no key of theirs.
      assert.deepEqual(await read(tenant(2, true), inWest()), [3]);
      // The scope's own values bind among the statement's: total > $1, the subquery's region and tenant, total < $n.
      assert.deepEqual(
        await read(tenant(1, false), {
          groups: [[{ column: 'total', op: '>', value: 20 }, ...inWest().groups[0]!, { column: 'total', op: '<', value: 80 }]],
        }),
        [1, 6],
      );
      const counted = await w.adapter.scopeTransaction(tenant(2, true), (tx) => tx.count(w.id('invoice'), inWest()));
      assert.equal(counted, 1);
    });

    test("a scoped reader's reads plan the subquery through the scope, and a table they cannot read keys nothing", async () => {
      const reads = await w.adapter.scopeReads(tenant(1, true));
      assert.deepEqual(ids((await reads.query({ table: w.id('invoice'), limit: 100, offset: 0, filter: inWest() })).rows), [1, 4, 5]);
      assert.equal(await reads.count(w.id('invoice'), inWest()), 3);
      const none = await w.adapter.scopeReads({ ...tenant(1, false), [w.id('customer')]: false });
      assert.deepEqual((await none.query({ table: w.id('invoice'), limit: 100, offset: 0, filter: inWest() })).rows, []);
    });

    /** A loader's db over the reader's scoped reads, as an App's page loader runs. */
    const load = async (reads: string[], where: object, readerScope: RowScope) => {
      const schema = await w.schema();
      const reader = await w.adapter.scopeReads(readerScope);
      return (await runPageLoader({
        name: 'west',
        loader: defineLoader({
          reads,
          load: async ({ db }: { db: Record<string, { where(where: object): PromiseLike<Row[]> }> }) => ids(await db.invoice!.where(where)),
        } as never) as never,
        reader: { query: reader.query, count: reader.count, aggregate: reader.aggregate },
        schema,
        logical: (local) => w.id(local),
        params: {},
        viewer: { roles: [] },
        now: new Date(),
      })) as number[];
    };

    test("a loader's test applies the reader's row policy inside the subquery", async () => {
      /* The policy shows gold customers only: 4 (west, basic) is hidden, so invoice 4 does not match, though a
         command, which reads every customer, finds it. */
      const gold: RowScope = {
        [w.id('invoice')]: true,
        [w.id('customer')]: { groups: [[{ column: 'Tier', op: '=', value: 'gold' } as Condition]] },
        [w.id('contact')]: true,
        [w.id('note')]: true,
      };
      assert.deepEqual(await load(DECLARED, west, gold), [1, 3, 5, 6]);
      assert.deepEqual(await load(DECLARED, { customer_id: { in: { from: 'customer', where: { region: 'east' } } } }, gold), []);
      assert.deepEqual(await load(DECLARED, west, tenant(2, true)), [3]);
      assert.deepEqual(await load(DECLARED, west, { ...gold, [w.id('customer')]: false }), []);
      await assert.rejects(load(['invoice'], west, gold), /reads customer, which is not among the tables this handle reads \(invoice\)/);
    });

    test("a narrowed resource named as `from` brings its own conditions inside the subquery, in a command's db and a scoped read", async () => {
      /* goldCustomer is customer narrowed to "Tier" = gold (appResources.ts physicalAny): a test against it selects the
         gold customers' keys only, whatever its own where says, as a read of goldCustomer lists only those rows. */
      const resources = createAppResources(
        w.adapter,
        await w.schema(),
        {
          invoice: w.id('invoice'),
          customer: w.id('customer'),
          goldCustomer: w.id('customer'),
          contact: w.id('contact'),
          note: w.id('note'),
        },
        [],
        [],
        { goldCustomer: 'Tier = gold' },
      );
      const reads = ['invoice', 'goldCustomer'];
      const catalog = commandCatalog(resources.schema, reads, (local) => local)!;
      const db = createCommandDb({
        tx: resources.adapter as never,
        catalog,
        read: reads,
        write: [],
        now: () => new Date(),
      }) as unknown as Record<string, Handle>;
      const gold = (where: object) => ({ customer_id: { in: { from: 'goldCustomer', where } } });
      // West alone is customers 1, 3 and 4; narrowed to gold, 4 is not among the keys, so invoice 4 is not read.
      assert.deepEqual(ids(await db.invoice!.where(gold({ region: 'west' }))), [1, 3, 5, 6]);
      assert.deepEqual(ids(await db.invoice!.where(gold({}))), [1, 3, 5, 6]);
      assert.equal(await db.invoice!.count(gold({ region: 'west' })), 4);
      // Customer 2 is east but basic: the narrowing still stands when the where asks for it by name.
      assert.deepEqual(ids(await db.invoice!.where(gold({ region: 'east' }))), []);
      assert.deepEqual(ids(await db.invoice!.where(gold({ Tier: 'basic' }))), []);
      // The plain table beside it is not narrowed.
      const plain = createCommandDb({
        tx: resources.adapter as never,
        catalog: commandCatalog(resources.schema, ['invoice', 'customer'], (local) => local)!,
        read: ['invoice', 'customer'],
        write: [],
        now: () => new Date(),
      }) as unknown as Record<string, Handle>;
      assert.deepEqual(ids(await plain.invoice!.where(west)), [1, 3, 4, 5, 6]);
      // Under a scope (mapAppScopedReads), the narrowing joins the scope's own rule inside the subquery.
      const all = Object.fromEntries(resources.schema.tables.map((table) => [table.id, true])) as RowScope;
      const scoped = await resources.adapter.scopeReads!({
        ...all,
        customer: { groups: [[{ column: 'tenant_id', op: '=', value: 1 } as Condition]] },
        goldCustomer: { groups: [[{ column: 'tenant_id', op: '=', value: 1 } as Condition]] },
      });
      const within: Filter = { groups: [[{ column: 'customer_id', op: 'in', within: { table: 'goldCustomer' } }]] };
      // Tenant 1's gold customer is 1 alone: invoices 1, 5 and 6 (6 is tenant 2's invoice, read whole here).
      assert.deepEqual(ids((await scoped.query({ table: 'invoice', limit: 100, offset: 0, filter: within })).rows), [1, 5, 6]);
      assert.equal(await scoped.count('invoice', within), 3);
    });
  });
}

describe('buildWhere without a hook keeps refusing an in-subquery', () => {
  const within: Condition = { column: 'customer_id', op: 'in', within: { table: 'customer' } };
  test('every call that is not wired stays fail-closed, on both styles', () => {
    for (const style of [ANSI_STYLE, POSTGRES_STYLE])
      assert.throws(() => buildWhere({ groups: [[within]] }, style), /cannot compare a column with another table's rows/);
  });
  test('a hook binds the subquery values in order with the rest of the statement', () => {
    const plan = () => ({ select: 'SELECT "w"."id" FROM "customer" "w"', column: (name: string) => `"w"."${name}"` });
    const where = buildWhere(
      {
        groups: [
          [
            { column: 'total', op: '>', value: 1 },
            { ...within, within: { table: 'customer', filter: { groups: [[{ column: 'region', op: '=', value: 'west' }]] } } },
            { column: 'total', op: '<', value: 9 },
          ],
        ],
      },
      POSTGRES_STYLE,
      1,
      undefined,
      undefined,
      undefined,
      undefined,
      false,
      undefined,
      false,
      undefined,
      plan,
    );
    assert.deepEqual(where.params, [1, 'west', 9]);
    assert.match(
      where.text,
      /"total" > \$1 AND "customer_id" IN \(SELECT "w"\."id" FROM "customer" "w" WHERE .*"w"\."region" = \$2.*\) AND "total" < \$3/,
    );
  });
  /* A tenant's reads validate the filter before it reaches the scope (tenantReadRuntime.ts); refused there, a page
     loader's in-subquery answered 403 tenant_context_unavailable. */
  test('the read validator accepts one level of in-subquery over plain comparisons, and nothing looser', () => {
    const west = { groups: [[{ column: 'region', op: '=', value: 'west' }]] };
    assertStructuredReadFilter({ groups: [[within]] }, 'column');
    assertStructuredReadFilter({ groups: [[{ ...within, within: { table: 'customer', filter: west } }]] }, 'column');
    const refused = (condition: object, field: 'column' | 'path' = 'column') =>
      assert.throws(() => assertStructuredReadFilter({ groups: [[condition]] }, field), /Invalid structured filter/);
    refused({ ...within, op: '=' });
    refused({ ...within, value: [1] });
    refused({ ...within, within: { table: '' } });
    refused({ ...within, within: { table: 'customer', where: 'region = west' } });
    refused({ ...within, within: { table: 'customer', filter: { groups: [[{ column: 'region', op: '=', value: { sql: 1 } }]] } } });
    refused({ ...within, within: { table: 'customer', filter: { groups: [[{ column: 'id', op: 'in', within: { table: 'invoice' } }]] } } });
    refused({ path: 'customer_id', op: 'in', within: { table: 'customer' } }, 'path');
  });
});

/* Checked by tsc, never run: `from` names a table the handle reads, its where names that table's columns, one level
   only, and a lookup's where has no `in` at all. */
type Customer = Readonly<{ id: number; region: string; Tier: string }>;
type Invoice = Readonly<{ id: number; customer_id: number; total: number }>;
type Tables = { readonly invoice: Invoice; readonly customer: Customer };
export async function typedInRows(
  invoice: ReadTable<Invoice, Tables>,
  writable: WriteTable<Invoice, Readonly<Record<string, Row>>, Tables>,
  lookup: LookupTable<Invoice>,
) {
  const found = await invoice.where({ customer_id: { in: { from: 'customer', where: { region: 'west', Tier: ['gold'] } } } });
  const counted = await invoice.count({ total: { gt: 1 }, customer_id: { in: { from: 'customer', where: { region: { not: 'east' } } } } });
  const moved = await writable.updateWhere({ customer_id: { in: { from: 'customer', where: { region: 'west' } } } }, { total: 0 });
  // @ts-expect-error A table the handle does not read.
  await invoice.where({ customer_id: { in: { from: 'note', where: {} } } });
  // @ts-expect-error A column the other table does not have.
  await invoice.where({ customer_id: { in: { from: 'customer', where: { nope: 1 } } } });
  // @ts-expect-error One level: no `in` inside the other table's where.
  await invoice.where({ customer_id: { in: { from: 'customer', where: { id: { in: { from: 'invoice', where: {} } } } } } });
  // @ts-expect-error A lookup reads one table: its where has no `in`.
  await lookup.where({ customer_id: { in: { from: 'customer', where: {} } } });
  return [found, counted, moved];
}

