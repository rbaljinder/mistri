import { test } from 'node:test';
import assert from 'node:assert/strict';
import { loadPostgresFixture, postgresFixture, seedPostgres } from './fixtures/apps/service-desk/seed-postgres.mjs';

const fixture = postgresFixture();

function recordingClient(options: { occupied?: boolean; failInsert?: boolean; wrongCount?: boolean; wrongForeignKeys?: boolean } = {}) {
  const calls: Array<{ sql: string; params?: unknown[] }> = [];
  return {
    calls,
    async query(sql: string, params?: unknown[]) {
      calls.push({ sql, params });
      if (sql.includes('pg_try_advisory_xact_lock')) return { rows: [{ acquired: true }] };
      if (sql.includes("nspname = 'public'")) return { rows: [{ oid: 2200 }] };
      if (sql.includes('SELECT 1 FROM pg_class')) return { rows: options.occupied ? [{ exists: 1 }] : [] };
      if (sql.startsWith('INSERT') && options.failInsert) throw new Error('Simulated insert failure');
      if (sql.includes('AS name, COUNT(*)'))
        return { rows: fixture.map((table) => ({ name: table.name, total: options.wrongCount ? -1 : table.data.length })) };
      if (sql.includes('FROM pg_constraint')) return { rows: [{ total: options.wrongForeignKeys ? 52 : 53 }] };
      return { rows: [] };
    },
  };
}

test('Atlas PostgreSQL fixture derives schema, native values and deterministic rows from SQLite', () => {
  assert.equal(fixture.length, 26);
  assert.equal(
    fixture.reduce((sum, table) => sum + table.foreignKeys.length, 0),
    53,
  );
  assert.equal(
    fixture.reduce((sum, table) => sum + table.data.length, 0),
    772,
  );
  assert.equal(
    fixture.reduce((sum, table) => sum + table.indexes.filter((index: { origin: string }) => index.origin === 'c').length, 0),
    53,
  );
  for (const table of fixture) {
    assert.match(table.create, /"id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
    for (const check of table.checks) assert.ok(table.create.includes(`CHECK (${check})`));
    assert.equal(table.columns.length, table.data[0].length);
  }
  const catalog = fixture.find((table) => table.name === 'catalog_item')!;
  assert.match(catalog.create, /"price" double precision NOT NULL/);
  assert.match(catalog.create, /"active" boolean NOT NULL DEFAULT true/);
  const approval = catalog.columns.indexOf('approval_required');
  const active = catalog.columns.indexOf('active');
  assert.equal(catalog.data[0][approval], false);
  assert.equal(catalog.data[1][approval], true);
  assert.equal(catalog.data[0][active], true);
  for (const name of ['incident', 'change_request', 'service_request', 'purchase_order']) {
    const table = fixture.find((table) => table.name === name)!;
    assert.match(table.create, /gen_random_uuid\(\)/);
    assert.doesNotMatch(table.create, /randomblob/);
    assert.match(table.create, /UNIQUE \("reference"\)/);
  }
  assert.match(fixture.find((table) => table.name === 'order_line')!.create, /received_quantity>=0 AND received_quantity<=quantity/);
  assert.match(
    fixture.find((table) => table.name === 'change_request')!.create,
    /ends_at IS NULL OR starts_at IS NULL OR ends_at>starts_at/,
  );
});

test('Atlas PostgreSQL load batches bound rows, resets every identity and commits after validation', async () => {
  const client = recordingClient();
  assert.deepEqual(await loadPostgresFixture(client, fixture), { tables: 26, foreignKeys: 53, rows: 772 });
  assert.equal(client.calls[0].sql, 'BEGIN');
  assert.equal(client.calls.at(-1)!.sql, 'COMMIT');
  const insertions = client.calls.filter((call) => call.sql.startsWith('INSERT'));
  assert.ok(insertions.length > 26, 'Large note table is split into batches');
  assert.ok(insertions.every((call) => call.sql.includes('$1') && call.params!.length > 0));
  assert.ok(
    insertions.every((call) => !call.sql.includes('Maya Chen')),
    'Fixture values stay out of SQL text',
  );
  assert.equal(client.calls.filter((call) => call.sql.startsWith('SELECT setval')).length, 26);
  assert.equal(
    client.calls.some((call) => call.sql === 'ROLLBACK'),
    false,
  );
});

test('Atlas PostgreSQL load refuses a nonempty public schema before DDL or inserts', async () => {
  const client = recordingClient({ occupied: true });
  await assert.rejects(loadPostgresFixture(client, fixture), /public schema is not empty/);
  assert.equal(client.calls.at(-1)!.sql, 'ROLLBACK');
  assert.equal(
    client.calls.some((call) => /^(CREATE|ALTER|INSERT)/.test(call.sql)),
    false,
  );
});

for (const options of [{ failInsert: true }, { wrongCount: true }, { wrongForeignKeys: true }]) {
  test(`Atlas PostgreSQL load rolls back ${Object.keys(options)[0]}`, async () => {
    const client = recordingClient(options);
    await assert.rejects(loadPostgresFixture(client, fixture));
    assert.equal(client.calls.at(-1)!.sql, 'ROLLBACK');
    assert.equal(
      client.calls.some((call) => call.sql === 'COMMIT'),
      false,
    );
  });
}

test('Atlas PostgreSQL entry point refuses missing configuration and redacts malformed URLs', async () => {
  await assert.rejects(seedPostgres(undefined), /PLANETSCALE_DATABASE_URL is required/);
  await assert.rejects(seedPostgres('postgres://secret-user:secret-password@[invalid'), (error) => {
    assert.ok(error instanceof Error);
    assert.match(error.message, /Atlas PostgreSQL seed failed/);
    assert.doesNotMatch(error.message, /secret|invalid/);
    return true;
  });
});
