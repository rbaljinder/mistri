const LIVE = process.env.TABLEWALK_TEST_PG;
const SCHEMA = 'any_rows';

type Row = Record<string, unknown>;
interface World {
  /** A local table name as this database ids it (schema-qualified on PostgreSQL). */
  id(table: string): string;
  readonly adapter: SqliteAdapter | PostgresAdapter;
  schema(): Promise<DatabaseSchema>;
  close(): Promise<void>;
}

/* Five invoices. Lines: invoice 1 has qty 3 and 9 (sku A), 2 has 1 (B), 3 has 7 (A) and 2 (B), 5 has 9 (B), 4 none.
   One payment, on invoice 3. A note (an undeclared child) on invoice 1. Ledger and LedgerEntry are mixed case. */
function statements(postgres: boolean): string[] {
  const pk = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  return [
    `CREATE TABLE invoice (id ${pk}, customer TEXT NOT NULL, status TEXT NOT NULL, total INTEGER NOT NULL)`,
    `CREATE TABLE line (id ${pk}, invoice_id INTEGER NOT NULL REFERENCES invoice (id), qty INTEGER NOT NULL, sku TEXT NOT NULL)`,
    `CREATE TABLE payment (id ${pk}, invoice_id INTEGER NOT NULL REFERENCES invoice (id), amount INTEGER NOT NULL)`,
    `CREATE TABLE audit_note (id ${pk}, invoice_id INTEGER NOT NULL REFERENCES invoice (id), body TEXT)`,
    `CREATE TABLE "Ledger" (id ${pk}, "OwnerId" INTEGER NOT NULL)`,
    `CREATE TABLE "LedgerEntry" (id ${pk}, "LedgerId" INTEGER NOT NULL REFERENCES "Ledger" (id), "EntryQty" INTEGER NOT NULL)`,
    `CREATE TABLE emp (id ${pk}, manager_id INTEGER REFERENCES emp (id), salary INTEGER NOT NULL)`,
    `CREATE TABLE shipment (id ${pk}, region TEXT NOT NULL, num INTEGER NOT NULL, UNIQUE (region, num))`,
    `CREATE TABLE parcel (id ${pk}, region TEXT NOT NULL, num INTEGER NOT NULL, weight INTEGER NOT NULL, FOREIGN KEY (region, num) REFERENCES shipment (region, num))`,
    `INSERT INTO emp VALUES (1, NULL, 20), (2, 1, 5), (3, 1, 9), (4, 2, 1)`,
    `INSERT INTO shipment VALUES (1, 'N', 1), (2, 'N', 2), (3, 'S', 1)`,
    `INSERT INTO parcel VALUES (1, 'N', 1, 3), (2, 'N', 1, 8), (3, 'S', 1, 9), (4, 'N', 2, 1)`,
    `INSERT INTO invoice VALUES (1, 'ana', 'open', 50), (2, 'ben', 'open', 5), (3, 'ana', 'open', 70), (4, 'cy', 'closed', 90), (5, 'ana', 'open', 80)`,
    `INSERT INTO line VALUES (1, 1, 3, 'A'), (2, 1, 9, 'A'), (3, 2, 1, 'B'), (4, 3, 7, 'A'), (5, 3, 2, 'B'), (6, 5, 9, 'B')`,
    `INSERT INTO payment VALUES (1, 3, 100)`,
    `INSERT INTO audit_note VALUES (1, 1, 'x')`,
    `INSERT INTO "Ledger" VALUES (1, 10), (2, 11), (3, 10)`,
    `INSERT INTO "LedgerEntry" VALUES (1, 1, 6), (2, 2, 1), (3, 3, 8)`,
  ];
}

async function sqliteWorld(): Promise<World> {
  const directory = mkdtempSync(join(tmpdir(), 'mistri-any-'));
  const file = join(directory, 'data.db');
  const db = new DatabaseSync(file);
  for (const statement of statements(false)) db.exec(statement);
  const adapter = new SqliteAdapter(file, 'any');
  return {
    id: (table) => table,
    adapter,
    schema: () => adapter.introspect(),
    async close() {
      await adapter.close();
      db.close();
      rmSync(directory, { recursive: true, force: true });
    },
  };
}

async function postgresWorld(): Promise<World> {
  const specifier = 'pg';
  const pg = (await import(specifier)) as { default?: { Client: never }; Client?: never };
  const Client = (pg.Client ?? pg.default?.Client)! as new (c: unknown) => {
    connect(): Promise<void>;
    query(sql: string, params?: readonly unknown[]): Promise<{ rows: Row[] }>;
    end(): Promise<void>;
  };
  const control = new Client({ connectionString: LIVE, statement_timeout: 60_000 });
  await control.connect();
  await control.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE; CREATE SCHEMA ${SCHEMA}`);
  await control.query(`SET search_path TO ${SCHEMA}`);
  for (const statement of statements(true)) await control.query(statement);
  const adapter = new PostgresAdapter(LIVE!, 'any', [SCHEMA]);
  return {
    id: (table) => `${SCHEMA}.${table}`,
    adapter,
    schema: () => adapter.introspect(),
    async close() {
      await adapter.close();
      await control.query(`DROP SCHEMA IF EXISTS ${SCHEMA} CASCADE`);
      await control.end();
    },
  };
}

const ids = (rows: readonly Row[]) => rows.map((row) => Number(row.id)).sort((a, b) => a - b);
const DECLARED = ['invoice', 'line', 'payment'];

function proofs(open: () => Promise<World>, label: string, skip: false | string = false) {
  describe(`any/no in a handler's db on ${label}`, { skip }, () => {
    let w: World;
    before(async () => {
      w = await open();
    });
    after(async () => {
      await w?.close();
    });

    /** A handle set over the raw adapter, as a command's (and a policy's) is: local names mapped to the database's. */
    const handles = async (
      reads: readonly string[],
      world = w,
      grant?: (schema: DatabaseSchema) => Parameters<typeof authorizeColumnWrites>[1],
    ) => {
      const schema = await world.schema();
      const catalog = commandCatalog(schema, reads, (local) => world.id(local));
      assert.ok(catalog, 'the catalog builds');
      const physical = (local: string) => world.id(local);
      /* A command's transaction is held to its grant's columns (columnGrants.ts) when the App names a grant. */
      const below = grant
        ? authorizeColumnWrites(schema, grant(schema), {
            query: (request: never) => world.adapter.query(request),
            count: (table: string, filter?: never) => world.adapter.count(table, filter),
          } as never)
        : world.adapter;
      const tx = {
        query: (request: { table: string; filter?: never }) =>
          below.query({ ...request, table: physical(request.table), filter: renamedAnyRows(request.filter, physical) } as never),
        count: (table: string, filter?: never) => below.count(physical(table), renamedAnyRows(filter, physical)),
      };
      return createCommandDb({ tx: tx as never, catalog, read: reads, write: [], now: () => new Date() }) as unknown as Record<
        string,
        {
          where(text: string): PromiseLike<Row[]> & { first(): Promise<Row | undefined>; sum(column: string): Promise<unknown> };
          count(text: string): Promise<number>;
        }
      >;
    };
    const invoices = async (text: string, reads: readonly string[] = DECLARED) => ids(await (await handles(reads)).invoice.where(text));

    // 1
    test('a command reads exactly the invoices with a matching line, and with none', async () => {
      assert.deepEqual(await invoices('any line where qty > 5'), [1, 3, 5]);
      assert.deepEqual(await invoices('no line where qty > 5'), [2, 4]);
      assert.deepEqual(await invoices('any line'), [1, 2, 3, 5]);
      assert.deepEqual(await invoices('no payment'), [1, 2, 4, 5]);
      assert.deepEqual(await invoices('any payment where amount >= 100'), [3]);
      const db = await handles(DECLARED);
      assert.equal(await db.invoice.count('any line where qty > 5'), 3);
      assert.equal(await db.invoice.count('no line where qty > 5'), 2);
      assert.equal((await db.invoice.where('any line where qty > 5').first())?.id, 1);
    });

    test("a command held to its grant's columns asks any and no, and a child column outside the grant is refused", async () => {
      const id = (table: string) => w.id(table);
      const grant = (readable: readonly string[], line: readonly string[]) => () => ({
        readable: new Set(readable.map(id)),
        writable: new Set<string>(),
        fields: new Map([[id('line'), { read: new Set(line), write: new Set<string>() }]]),
      });
      const granted = await handles(DECLARED, w, grant(DECLARED, ['id', 'invoice_id', 'qty']));
      assert.deepEqual(ids(await granted.invoice.where('any line where qty > 5')), [1, 3, 5]);
      assert.deepEqual(ids(await granted.invoice.where('no line where qty > 5')), [2, 4]);
      assert.equal(await granted.invoice.count('no payment'), 4);
      // sku is not among the columns this grant reads on line; below, payment is not a table the narrower grant reads.
      await assert.rejects(
        async () => await granted.invoice.where('any line where sku = "A"'),
        (error: Error) => error.name === 'AppAccessDenied',
      );
      const narrower = await handles(DECLARED, w, grant(['invoice', 'line'], ['id', 'invoice_id', 'qty']));
      await assert.rejects(narrower.invoice.count('any payment'), (error: Error) => error.name === 'AppAccessDenied');
    });

    test('parent conditions before and after the any, and a value inside it, bind in the order they are written', async () => {
      // $1 total, $2 qty, $3 sku, $4 status, $5 customer, $6 total: a misnumbered placeholder reads a different value and fails here.
      assert.deepEqual(
        await invoices('total > 10 and any line where (qty > 5 and sku = "A") and status = open and customer = ana and total < 60'),
        [1],
      );
      assert.deepEqual(await invoices('customer = ana and no line where sku = "B" and total >= 50'), [1]);
      assert.deepEqual(await invoices('any line where (qty > 5 and sku = "B") or total = 90'), [4, 5]);
      assert.deepEqual(await invoices('any line where qty > 8 and total < 75 or any payment and total < 75'), [1, 3]);
      // The same conditions twice in two groups: the shared one is said once, and the numbering holds.
      assert.deepEqual(
        await invoices('status = open and any line where qty = 9 or status = open and any payment where amount = 100'),
        [1, 3, 5],
      );
      assert.deepEqual(await invoices('total > 10 and any line where qty > 5 sort total desc limit 2'), [3, 5]);
    });

    test('a loader-shaped read of the same condition through page() and a keyset boundary still numbers', async () => {
      const db = (await handles(DECLARED)).invoice as unknown as {
        where(text: string): { page(o: { size: number; after?: unknown }): Promise<{ rows: Row[]; next?: unknown }> };
      };
      const first = await db.where('any line where (qty > 5 and sku = "A")').page({ size: 1 });
      assert.deepEqual(ids(first.rows), [1]);
      const second = await db.where('any line where (qty > 5 and sku = "A")').page({ size: 1, after: first.next });
      assert.equal(second.rows.length, 1);
      assert.equal(Number(second.rows[0].id), 3);
    });

    // 6
    test('a mixed-case table and column are quoted on both the parent and the child side', async () => {
      const db = await handles(['Ledger', 'LedgerEntry']);
      assert.deepEqual(ids(await db.Ledger.where('any LedgerEntry where EntryQty > 5')), [1, 3]);
      assert.deepEqual(ids(await db.Ledger.where('no LedgerEntry where EntryQty > 5')), [2]);
      assert.deepEqual(ids(await db.Ledger.where('OwnerId = 10 and any LedgerEntry where EntryQty > 7')), [3]);
    });

    test('a self-referencing key finds the rows that point at the row, from the manager side', async () => {
      const db = await handles(['emp']);
      assert.deepEqual(ids(await db.emp.where('any emp where salary > 6')), [1]);
      assert.deepEqual(ids(await db.emp.where('any emp')), [1, 2]);
      assert.deepEqual(ids(await db.emp.where('no emp')), [3, 4]);
      assert.deepEqual(ids(await db.emp.where('no emp where salary > 6')), [2, 3, 4]);
    });

    test('a composite key pairs its columns, so a child matching only one of them does not count', async () => {
      const db = await handles(['shipment', 'parcel']);
      assert.deepEqual(ids(await db.shipment.where('any parcel where weight > 5')), [1, 3]);
      assert.deepEqual(ids(await db.shipment.where('no parcel where weight > 5')), [2]);
      assert.deepEqual(ids(await db.shipment.where('any parcel')), [1, 2, 3]);
    });

    // 4
    test('an any naming a child outside the declared reads is refused by name, and nothing is read', async () => {
      const db = await handles(['invoice', 'line']);
      await assert.rejects(
        async () => db.invoice.where('any audit_note'),
        /"any audit_note" asks about audit_note, which is not among the tables this handle reads \(invoice, line\); declare it in read or write/,
      );
      await assert.rejects(async () => db.invoice.where('no payment where amount > 1'), /"no payment" asks about payment/);
      await assert.rejects(async () => db.invoice.count('any audit_note'), /asks about audit_note/);
      // A read declared only on the table asked about: the child still has to be among them.
      const only = await handles(['invoice']);
      await assert.rejects(async () => only.invoice.where('any line'), /which is not among the tables this handle reads \(invoice\)/);
    });

    // 5
    test('a reference path is still refused, at the parent and inside the child', async () => {
      const db = await handles(DECLARED);
      await assert.rejects(async () => db.line.where('invoice_id.customer = ana'), /is a path|not a column|only/);
      await assert.rejects(async () => db.line.where('any invoice_id.customer'), /./);
      await assert.rejects(async () => db.invoice.where('any line where invoice_id.customer = ana'), /path|only|not a stored column/);
      await assert.rejects(async () => db.invoice.where('any line where any payment'), /no reference to line|own rows/);
    });

    test('a sum over an any is refused with a message that says what to do', async () => {
      const db = await handles(DECLARED);
      const sum = db.invoice.where('any line where qty > 5').sum('total');
      await assert.rejects(sum, (error: Error) =>
        /read the rows with an "any"\/"no" where, or count them/.test(String(refusalCause(error) ?? '')),
      );
    });
  });

  describe(`any/no in a loader's db on ${label}: the child is read through the reader's row scope`, { skip }, () => {
    let w: World;
    before(async () => {
      w = await open();
    });
    after(async () => {
      await w?.close();
    });

    /** What the reader may read: every table whole, except `line`, of which they see the A lines only. */
    const scope = (): RowScope => ({
      [w.id('invoice')]: true,
      [w.id('payment')]: true,
      [w.id('audit_note')]: true,
      [w.id('Ledger')]: true,
      [w.id('LedgerEntry')]: true,
      [w.id('line')]: { groups: [[{ column: 'sku', op: '=', value: 'A' } as Condition]] },
    });
    const load = async (reads: string[], text: string, readerScope: RowScope = scope(), table = 'invoice') => {
      const schema = await w.schema();
      const reader = await w.adapter.scopeReads(readerScope);
      const found = (await runPageLoader({
        name: 'tally',
        loader: defineLoader({
          reads,
          load: async ({ db }: { db: Record<string, { where(text: string): PromiseLike<Row[]> }> }) => ids(await db[table].where(text)),
        } as never) as never,
        reader: { query: reader.query, count: reader.count, aggregate: reader.aggregate },
        schema,
        logical: (local) => w.id(local),
        params: {},
        viewer: { roles: [] },
        now: new Date(),
      })) as number[];
      return found;
    };

    test("a loader's any is satisfied only by rows the reader can see", async () => {
      // As a command reads them (every line), invoice 5 has a qty-9 line; this reader sees only the A lines, and 5's is B.
      assert.deepEqual(await load(DECLARED, 'any line where qty > 5'), [1, 3]);
      assert.deepEqual(await load(DECLARED, 'no line where qty > 5'), [2, 4, 5]);
      assert.deepEqual(await load(DECLARED, 'any line'), [1, 3]);
      // The invoice's own scope narrows the parent as it narrows any list.
      const narrowed = { ...scope(), [w.id('invoice')]: { groups: [[{ column: 'customer', op: '=', value: 'ana' } as Condition]] } };
      assert.deepEqual(await load(DECLARED, 'any line where qty > 5', narrowed), [1, 3]);
      assert.deepEqual(await load(DECLARED, 'no line where qty > 5', narrowed), [5]);
      // A reader with no line rows at all sees no invoice with one.
      assert.deepEqual(await load(DECLARED, 'any line', { ...scope(), [w.id('line')]: false }), []);
      assert.deepEqual(await load(DECLARED, 'no line', { ...scope(), [w.id('line')]: false }), [1, 2, 3, 4, 5]);
    });

    test('values bind in order around an any under a scope, and a mixed-case table works', async () => {
      assert.deepEqual(
        await load(DECLARED, 'total > 10 and any line where (qty > 5 and sku = "A") and status = open and customer = ana and total < 60'),
        [1],
      );
      assert.deepEqual(
        await load(DECLARED, 'status = open and any line where qty = 9 or status = open and any payment where amount = 100'),
        [1, 3],
      );
      assert.deepEqual(await load(['Ledger', 'LedgerEntry'], 'any LedgerEntry where EntryQty > 5', scope(), 'Ledger'), [1, 3]);
    });

    test("a child outside the loader's reads is refused, and a child outside the reader's catalog is refused", async () => {
      await assert.rejects(load(['invoice', 'line'], 'any payment'), /"any payment" asks about payment/);
      // The reader's catalog is pruned: a line table they may not read is no relation of theirs.
      const schema = await w.schema();
      const pruned: DatabaseSchema = { ...schema, tables: schema.tables.filter((table) => table.id !== w.id('line')) };
      const reader = await w.adapter.scopeReads(scope());
      await assert.rejects(
        runPageLoader({
          name: 'tally',
          loader: defineLoader({
            reads: ['invoice'],
            load: async ({ db }: { db: Record<string, { where(text: string): PromiseLike<Row[]> }> }) => db.invoice.where('any line'),
          } as never) as never,
          reader: { query: reader.query, count: reader.count, aggregate: reader.aggregate },
          schema: pruned,
          logical: (local) => w.id(local),
          params: {},
          viewer: { roles: [] },
          now: new Date(),
        }),
        /./,
      );
    });

    const asks = (via: string, filter?: Condition[][]): Condition => ({
      column: 'x',
      op: 'isNotNull',
      any: { via, ...(filter ? { filter: { groups: filter } } : {}) },
    });
    const qty = [[{ column: 'qty', op: '>', value: 5 } as Condition]];

    test("a scoped write transaction's read plans the child through the same scope", async () => {
      const found = await w.adapter.scopeTransaction(scope(), async (tx) =>
        ids(
          (
            await tx.query({
              table: w.id('invoice'),
              limit: 100,
              offset: 0,
              filter: { groups: [[asks(`${w.id('line')}.invoice_id`, qty)]] },
            })
          ).rows,
        ),
      );
      assert.deepEqual(found, [1, 3]);
      const counted = await w.adapter.scopeTransaction(scope(), (tx) =>
        tx.count(w.id('invoice'), { groups: [[{ ...asks(`${w.id('line')}.invoice_id`, qty), op: 'isNull' }]] }),
      );
      assert.equal(counted, 3);
    });

    test('a hostile any is refused, never dropped: an unknown child, a column the child lacks, a second any, a column on the right', async () => {
      const reads = await w.adapter.scopeReads(scope());
      const read = (condition: Condition) =>
        reads.query({ table: w.id('invoice'), limit: 10, offset: 0, filter: { groups: [[condition]] } });
      await assert.rejects(read(asks(`${w.id('ghost')}.invoice_id`)), /cannot ask about the rows that point at it/);
      await assert.rejects(read(asks(`${w.id('line')}.nope`)), /cannot ask about the rows that point at it/);
      await assert.rejects(
        read(asks(`${w.id('line')}.invoice_id`, [[{ column: 'nope', op: '=', value: 1 }]])),
        /Unknown column in a related-rows test/,
      );
      await assert.rejects(
        read(asks(`${w.id('line')}.invoice_id`, [[asks(`${w.id('payment')}.invoice_id`)]])),
        /cannot ask about the rows that point at it/,
      );
      await assert.rejects(
        read(asks(`${w.id('line')}.invoice_id`, [[{ column: 'qty', op: '=', other: 'id' } as Condition]])),
        /cannot ask about the rows that point at it/,
      );
      // The raw adapter, which reads the child as it reads the parent, holds the same line.
      await assert.rejects(
        w.adapter.query({ table: w.id('invoice'), limit: 10, offset: 0, filter: { groups: [[asks(`${w.id('ghost')}.invoice_id`)]] } }),
        /cannot ask about the rows that point at it/,
      );
      await assert.rejects(
        w.adapter.query({
          table: w.id('invoice'),
          limit: 10,
          offset: 0,
          filter: { groups: [[asks(`${w.id('line')}.invoice_id`, [[{ column: 'nope', op: '=', value: 1 }]])]] },
        }),
        /Unknown column in a related-rows test/,
      );
    });
  });
}

describe('buildWhere without a hook keeps refusing an any', () => {
  const asks: Condition = { column: 'x', op: 'isNotNull', any: { via: 'line.invoice_id' } };
  test('every call that is not wired stays fail-closed, on both styles', () => {
    for (const style of [ANSI_STYLE, POSTGRES_STYLE])
      assert.throws(() => buildWhere({ groups: [[asks]] }, style), /cannot ask about the rows that point at it/);
  });
  test('an inline hook binds the child values in order and a second any inside is refused', () => {
    const rows = { relation: '"line"', alias: '"c"', on: '"c"."invoice_id" = "invoice"."id"', column: (n: string) => `"c"."${n}"` };
    const where = buildWhere(
      {
        groups: [
          [
            { column: 'total', op: '>', value: 1 },
            { column: 'x', op: 'isNotNull', any: { via: 'line.invoice_id', filter: { groups: [[{ column: 'qty', op: '>', value: 5 }]] } } },
            { column: 'status', op: '=', value: 'open' },
          ],
        ],
      },
      POSTGRES_STYLE,
      1,
      undefined,
      undefined,
      undefined,
      undefined,
      false,
      undefined,
      false,
      () => rows,
    );
    assert.deepEqual(where.params, [1, 5, 'open']);
    assert.match(where.text, /"total" > \$1 AND EXISTS \(SELECT 1 FROM "line" "c" WHERE .* AND \("c"\."qty" > \$2\)\) AND "status" = \$3/);
    assert.throws(
      () =>
        buildWhere(
          { groups: [[{ column: 'x', op: 'isNotNull', any: { via: 'a.b', filter: { groups: [[asks]] } } }]] },
          ANSI_STYLE,
          1,
          undefined,
          undefined,
          undefined,
          undefined,
          false,
          undefined,
          false,
          () => rows,
        ),
      /cannot ask about the rows that point at it/,
    );
  });
});

