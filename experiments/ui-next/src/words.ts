export type Words = typeof ENGLISH;

/* The words in use. Read at each draw, so `setWords` before a draw is what that draw says. */
export const words: Words = { ...ENGLISH };

export function setWords(given: Partial<Words>): void {
  Object.assign(words, given);
}

/* The words as they are before any are set: for a test, and for a page that goes back to English. */
export function resetWords(): void {
  Object.assign(words, ENGLISH);
}
