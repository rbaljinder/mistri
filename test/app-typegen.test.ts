        '  views: { products: listView("product", { show: ["name", "lines"] }) }, home: "products" } satisfies App;',
        'export const margin = (row: Rows["product"]) => (row.price ?? 0) - (row.cost ?? 0);',
        'export const moved = (row: Rows["ledger"]) => row.qty;',
        '// @ts-expect-error A hidden column is never shown.',
        'export const shown = { name: "Shop", views: { products: listView("product", { show: ["cost"] }) }, home: "products" } satisfies App;',
