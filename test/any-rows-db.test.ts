/**
 * `any`/`no` in a handler's, a loader's and a policy's `db.<table>.where` (commandDb.ts): the rows that point at the
 * one read, asked as an EXISTS where the read executes.
 *
 * A command's and a policy's reads are the raw adapter's, so the child is read as the parent is, unscoped; the
 * declared reads are the only bound, and a child outside them is refused by name. A loader's are the reader's scoped
 * reads, so the child is planned through the reader's row scope and a row they cannot see does not satisfy an `any`.
 * SQLite always; PostgreSQL when `TABLEWALK_TEST_PG` names a disposable server (the schema `any_rows`, dropped before
 * and after, so a mixed-case table and column are proved against the real quoting).
 */
