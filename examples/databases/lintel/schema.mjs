/**
 * Lintel's business schema, written once for PostgreSQL and SQLite.
 *
 * PostgreSQL is the target: real dates and timestamps, bytea photos, identity
 * keys. SQLite gets the same tables, names and CHECKs with its own spellings
 * of those types, so the App's tests and a quick local try run on a file.
 * `ddl(dialect)` returns the statements in foreign-key order.
 *
 * Money is whole cents in an integer (`rent`, `amount`, `unit_cost`), so a
 * ledger never rounds: the App draws it as dollars (`minor: true`). The rules
 * that matter most are the database's as well as the App's: a part's stock
 * never goes below zero, a lease is charged its rent once a month, and a
 * payment's reference is the processor's and arrives once.
 */

const DIALECTS = {
  postgres: {
    id: 'id integer generated by default as identity primary key',
    date: 'date',
    ts: 'timestamp',
    bytes: 'bytea',
    yes: 'true',
    no: 'false',
  },
  sqlite: {
    id: 'id INTEGER PRIMARY KEY',
    date: 'DATE',
    ts: 'TIMESTAMP',
    bytes: 'BLOB',
    yes: '1',
    no: '0',
  },
};

/** The tables in foreign-key order, as [name, statement]. */
export function ddl(dialect) {
  const d = DIALECTS[dialect];
  if (!d) throw new Error(`Unknown dialect ${dialect}`);
  const { id, date, ts, bytes, yes, no } = d;
  const version = 'version integer NOT NULL DEFAULT 0';
  const cents = (name) => `${name} integer NOT NULL CHECK (${name} >= 0)`;
  return [
    [
      'staff',
      `CREATE TABLE staff (${id}, name text NOT NULL, email text NOT NULL UNIQUE, phone text,
        role text NOT NULL CHECK (role IN ('manager', 'leasing', 'technician', 'accountant')),
        title text NOT NULL, active boolean NOT NULL DEFAULT ${yes})`,
    ],
    [
      'property',
      `CREATE TABLE property (${id}, name text NOT NULL UNIQUE, address text NOT NULL, city text NOT NULL,
        state text NOT NULL, zip text NOT NULL, kind text NOT NULL CHECK (kind IN ('apartments', 'lofts', 'townhomes')),
        year_built integer NOT NULL, manager_id integer REFERENCES staff(id), description text)`,
    ],
    [
      'property_photo',
      `CREATE TABLE property_photo (${id}, property_id integer NOT NULL REFERENCES property(id), position integer NOT NULL,
        alt text NOT NULL, file_name text NOT NULL, content_type text NOT NULL, byte_size integer NOT NULL,
        data ${bytes} NOT NULL, thumbnail ${bytes})`,
    ],
    [
      'unit',
      `CREATE TABLE unit (${id}, property_id integer NOT NULL REFERENCES property(id), number text NOT NULL, code text NOT NULL UNIQUE,
        floor integer NOT NULL, bedrooms integer NOT NULL CHECK (bedrooms >= 0), bathrooms numeric(3,1) NOT NULL,
        sqft integer NOT NULL CHECK (sqft > 0), ${cents('market_rent')},
        status text NOT NULL DEFAULT 'vacant' CHECK (status IN ('occupied', 'notice', 'vacant', 'turnover')),
        listed boolean NOT NULL DEFAULT ${no}, available_on ${date}, headline text, description text, ${version},
        UNIQUE (property_id, number))`,
    ],
    [
      'resident',
      `CREATE TABLE resident (${id}, name text NOT NULL, email text NOT NULL UNIQUE, phone text,
        email_ok boolean NOT NULL DEFAULT ${yes}, language text NOT NULL DEFAULT 'en' CHECK (language IN ('en', 'es')),
        since ${date} NOT NULL)`,
    ],
    [
      'lease',
      `CREATE TABLE lease (${id}, unit_id integer NOT NULL REFERENCES unit(id),
        resident_id integer NOT NULL REFERENCES resident(id), start_on ${date} NOT NULL, end_on ${date} NOT NULL,
        ${cents('rent')}, ${cents('deposit')},
        status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'notice', 'ended')),
        signed_on ${date}, notice_on ${date}, ended_on ${date}, ${version}, CHECK (end_on > start_on))`,
    ],
    [
      'charge',
      // One charge of a kind for a lease's month: the rent job may run twice, the second finds it there.
      `CREATE TABLE charge (${id}, lease_id integer NOT NULL REFERENCES lease(id),
        kind text NOT NULL CHECK (kind IN ('rent', 'late_fee', 'utility', 'repair', 'other')), period text NOT NULL,
        description text NOT NULL, due_on ${date} NOT NULL, amount integer NOT NULL CHECK (amount > 0),
        status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'paid', 'waived')),
        posted_on ${date} NOT NULL, paid_on ${date}, waived_reason text, ${version},
        UNIQUE (lease_id, kind, period))`,
    ],
    [
      'payment',
      `CREATE TABLE payment (${id}, lease_id integer NOT NULL REFERENCES lease(id), charge_id integer REFERENCES charge(id),
        received_on ${date} NOT NULL, amount integer NOT NULL CHECK (amount > 0),
        method text NOT NULL CHECK (method IN ('ach', 'card', 'check', 'cash')), reference text NOT NULL UNIQUE)`,
    ],
    [
      'part',
      `CREATE TABLE part (${id}, sku text NOT NULL UNIQUE, name text NOT NULL,
        category text NOT NULL CHECK (category IN ('plumbing', 'electrical', 'appliance', 'hvac', 'hardware', 'paint')),
        on_hand integer NOT NULL DEFAULT 0 CHECK (on_hand >= 0), reorder_at integer NOT NULL DEFAULT 0,
        ${cents('unit_cost')}, bin text, ${version})`,
    ],
    [
      'part_receipt',
      `CREATE TABLE part_receipt (${id}, part_id integer NOT NULL REFERENCES part(id),
        quantity integer NOT NULL CHECK (quantity > 0), received_on ${date} NOT NULL, vendor text NOT NULL)`,
    ],
    [
      'maintenance_request',
      `CREATE TABLE maintenance_request (${id}, unit_id integer NOT NULL REFERENCES unit(id),
        resident_id integer REFERENCES resident(id), title text NOT NULL, description text,
        category text NOT NULL CHECK (category IN ('plumbing', 'electrical', 'appliance', 'hvac', 'general')),
        priority text NOT NULL DEFAULT 'normal' CHECK (priority IN ('low', 'normal', 'urgent')),
        status text NOT NULL DEFAULT 'new'
          CHECK (status IN ('new', 'triaged', 'scheduled', 'in_progress', 'on_hold', 'completed', 'closed', 'cancelled')),
        assigned_to integer REFERENCES staff(id), entry_ok boolean NOT NULL DEFAULT ${no},
        reported_on ${date} NOT NULL, scheduled_on ${date}, completed_on ${date}, resolution text,
        status_since ${ts}, ${version})`,
    ],
    [
      'request_part',
      `CREATE TABLE request_part (${id}, request_id integer NOT NULL REFERENCES maintenance_request(id),
        part_id integer NOT NULL REFERENCES part(id), quantity integer NOT NULL CHECK (quantity > 0), used_on ${date} NOT NULL)`,
    ],
    [
      'request_note',
      `CREATE TABLE request_note (${id}, request_id integer NOT NULL REFERENCES maintenance_request(id),
        kind text NOT NULL CHECK (kind IN ('resident', 'staff', 'internal')), author text NOT NULL, body text NOT NULL,
        sent_at ${ts} NOT NULL)`,
    ],
    [
      'viewing',
      `CREATE TABLE viewing (${id}, unit_id integer REFERENCES unit(id), reference text NOT NULL UNIQUE,
        name text NOT NULL, email text NOT NULL, phone text, preferred_on ${date} NOT NULL, message text,
        status text NOT NULL DEFAULT 'requested' CHECK (status IN ('requested', 'confirmed', 'completed', 'cancelled')),
        received_at ${ts} NOT NULL, ${version})`,
    ],
  ];
}

