/**
 * Files beside an inbound delivery's input (`defineInbound({ files })`,
 * jobs/inboundHost.ts): a signed body carries `files: [{ name, type, content }]`
 * in base64, each checked against the named file resource's rule, and the
 * command's handler receives them as `ctx.files` to store. The body cap is
 * raised only for an endpoint that declares files; one that does not keeps
 * 256 KiB. On each engine, over a real loopback server.
 */
