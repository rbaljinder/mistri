process.env.MISTRI_SECRETS_KEY ??= 'a-secrets-key-for-tests-that-is-long-enough';
const SECRET = 'docs-webhook-secret-0123456789abcdef';
const DATABASE = `integration_files_${randomUUID().replaceAll('-', '')}`;
after(async () => {
  if (process.env.TABLEWALK_TEST_PG) await dropDedicatedPostgresDatabase(DATABASE);
});

const sign = (secret: string, at: number, body: Buffer) => createHmac('sha256', secret).update(`${at}.`).update(body).digest('hex');

/* A provider that sends its event as the form's fields and signs the whole body: `x-docs-signature: t=<s>,v1=<hex>`. */
const docs = () =>
  defineIntegration({
    name: 'docs',
    secrets: ['webhookSecret'],
    client: () => ({}),
    actions: {},
    webhooks: {
      signing: 'webhookSecret',
      verify({ headers, body, form }, { secrets }) {
        const parts = Object.fromEntries(
          String(headers['x-docs-signature'] ?? '')
            .split(',')
            .map((part) => part.split('=') as [string, string]),
        );
        const at = Number(parts.t);
        if (!form || !Number.isInteger(at) || parts.v1 !== sign(secrets.webhookSecret, at, body)) return null;
        return { id: form.id!, type: form.type!, at: at * 1000, data: { ref: form.ref } };
      },
      events: { received: { type: 'doc.received', payload: shape({ ref: text() }) } },
    },
  });

const file = { content: 'data', name: 'file_name', type: 'content_type', size: 'byte_size' };
const intake = defineCommand({
  source: 'lab',
  target: 'scan',
  targets: 'none',
  // The field's own declaration is what bounds the callback's files: one or two PDFs.
  input: { ref: field.text(), scans: field.files('scan', { min: 1, max: 2, accept: 'application/pdf' }) },
  output: commandShape({ stored: number({ min: 0 }) }),
  async handle({ db }, input) {
    for (const each of input.scans) await db.scan.insertFile(each, { ref: input.ref });
    return { stored: input.scans.length };
  },
});

const SQLITE = `CREATE TABLE cb_scan (id INTEGER PRIMARY KEY, ref TEXT NOT NULL, file_name TEXT NOT NULL, content_type TEXT NOT NULL,
    byte_size INTEGER NOT NULL, data BLOB);`;
const POSTGRES = `CREATE TABLE public.cb_scan (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ref text NOT NULL,
    file_name text NOT NULL, content_type text NOT NULL, byte_size integer NOT NULL, data bytea);`;

interface Fixture {
  /** A multipart body: its fields, then its files `[part name, file name, content type, bytes]`. */
  body: (fields: Record<string, string>, files: Array<[string, string, string, Buffer]>) => { body: Buffer; type: string };
  /** Sends a body signed (or not, or as another body) at the fixture's clock. */
  send: (made: { body: Buffer; type: string }, options?: { signed?: Buffer | false }) => Promise<Response>;
  rows: () => Promise<Array<{ ref: string; file_name: string; content_type: string; data: Buffer }>>;
}

async function fixture(dialect: TenantDialect, run: (f: Fixture) => Promise<void>) {
  const engine = await openTenantEngine(dialect, { tables: ['cb_scan'], sqlite: SQLITE, postgres: POSTGRES, database: DATABASE });
  const registry = new Registry();
  let server: ReturnType<typeof createApp> | undefined;
  let store: IntegrationStore | undefined;
  try {
    await engine.migrateCommandJournal();
    if (dialect === 'sqlite') provisionSqliteIntegrations(engine.path);
    else await provisionPostgresIntegrations(engine.url);
    store = await openIntegrationStore(dialect === 'sqlite' ? { sqlite: engine.path } : { postgres: engine.url });
    const commands = defineCommands({ intake });
    registry.add({ id: 'private-db', name: 'Lab', url: engine.path || engine.url, writable: true, source: 'config' });
    const app = parseAppConfig(
      {
        id: 'lab',
        name: 'Lab',
        sources: { lab: { connection: 'private-db' } },
        // 2 KiB: a callback's file past it is the resource's 413, as an upload's would be.
        resources: { scan: { physical: engine.id('cb_scan'), access: 'write', file: { ...file, maxBytes: 2048 } } },
        auth: { roles: { staff: { read: true }, integration: { read: true, service: true, commands: ['intake'] } } },
        views: { scans: { kind: 'list', from: 'scan' } },
        home: 'scans',
      },
      'integration callback files fixture',
    );
    const resources = await loadAppRuntimeResources(registry, app, 'private-db');
    const binding = bindBusinessCommands({ app, registry: commands, resources, writableConnection: () => true });
    const module = pinJobs(
      capturedJobModule(
        defineJobs(
          {},
          {
            principals: { sender: { roles: ['integration'] } },
            integrations: { use: [docs()], webhooks: { docs: { runAs: 'sender', events: { received: 'intake' } } } },
          },
        ),
      ),
      commands,
    );
    const clock = { now: Date.parse('2026-11-18T12:00:00Z') };
    const declared = captureIntegrations(
      { use: [docs()], webhooks: { docs: { runAs: 'sender', events: { received: 'intake' } } } },
      module.principals,
      (message) => {
        throw new Error(message);
      },
    );
    const runtime = createIntegrationRuntime({ appId: 'lab', declared, store, now: () => clock.now });
    await saveIntegrationSettings(runtime, '', 'owner', { integration: 'docs', secrets: { webhookSecret: SECRET } });
    const host = createInboundHost({
      endpoints: integrationEndpoints(runtime, commands, app),
      appId: 'lab',
      principals: module.principals,
      bind: async () => ({ binding, release() {} }),
      deliveries: store,
      now: () => clock.now,
      warn: () => {},
    });
    server = createApp({ registry, bound: { host: '127.0.0.1', port: 0 }, inbound: host });
    server.listen(0, '127.0.0.1');
    await new Promise((resolve) => server!.once('listening', resolve));
    const url = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
    const body: Fixture['body'] = (fields, files) => {
      const boundary = `----docs${randomUUID().replaceAll('-', '')}`;
      const parts: Buffer[] = [];
      for (const [name, value] of Object.entries(fields))
        parts.push(Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="${name}"\r\n\r\n${value}\r\n`));
      for (const [name, filename, type, bytes] of files)
        parts.push(
          Buffer.from(
            `--${boundary}\r\nContent-Disposition: form-data; name="${name}"; filename="${filename}"\r\nContent-Type: ${type}\r\n\r\n`,
          ),
          bytes,
          Buffer.from('\r\n'),
        );
      parts.push(Buffer.from(`--${boundary}--\r\n`));
      return { body: Buffer.concat(parts), type: `multipart/form-data; boundary=${boundary}` };
    };
    const at = Math.floor(clock.now / 1000);
    const send: Fixture['send'] = ({ body: bytes, type }, options = {}) =>
      fetch(`${url}/api/inbound/docs`, {
        method: 'POST',
        body: new Uint8Array(bytes),
        headers: {
          'content-type': type,
          ...(options.signed === false ? {} : { 'x-docs-signature': `t=${at},v1=${sign(SECRET, at, options.signed ?? bytes)}` }),
        },
      });
    const rows: Fixture['rows'] = async () =>
      (await engine.all('SELECT ref, file_name, content_type, data FROM cb_scan ORDER BY id')).map((row) => ({
        ref: String(row.ref),
        file_name: String(row.file_name),
        content_type: String(row.content_type),
        data: Buffer.from(row.data as Uint8Array),
      }));
    await run({ body, send, rows });
  } finally {
    await new Promise((resolve) => (server ? server.close(resolve) : resolve(undefined)));
    await store?.close();
    await registry.closeAll();
    await engine.close();
  }
}

const PDF = Buffer.from('%PDF-1.7 a signed form');

for (const { dialect, skip } of TENANT_DIALECTS)
  describe(`integration callback files on ${dialect}`, { skip }, () => {
    test('a signed multipart callback delivers a file the command stores with insertFile, and a replay stores nothing twice', async () => {
      await fixture(dialect, async (f) => {
        const made = f.body({ id: 'evt-1', type: 'doc.received', ref: 'form-7' }, [['scans', 'form 7.pdf', 'application/pdf', PDF]]);
        const reply = await f.send(made);
        assert.equal(reply.status, 204, await reply.clone().text());
        const rows = await f.rows();
        assert.equal(rows.length, 1);
        assert.equal(rows[0]!.ref, 'form-7');
        assert.equal(rows[0]!.file_name, 'form 7.pdf');
        assert.equal(rows[0]!.content_type, 'application/pdf');
        assert.deepEqual(rows[0]!.data, PDF);
        // The same bytes again are the provider's retry: the command's receipt answers it.
        assert.equal((await f.send(made)).status, 204);
        assert.equal((await f.rows()).length, 1);
      });
    });

    test('a file past the resource cap is 413, a type the field does not take is 415, and neither stores a row', async () => {
      await fixture(dialect, async (f) => {
        const big = f.body({ id: 'evt-2', type: 'doc.received', ref: 'big' }, [
          ['scans', 'big.pdf', 'application/pdf', Buffer.alloc(3000, 0x41)],
        ]);
        assert.equal((await f.send(big)).status, 413);
        const wrong = f.body({ id: 'evt-3', type: 'doc.received', ref: 'wrong' }, [
          ['scans', 'note.txt', 'text/plain', Buffer.from('hello')],
        ]);
        assert.equal((await f.send(wrong)).status, 415);
        // More files than the field's max is the command's input refusal, as a form's would be.
        const many = f.body(
          { id: 'evt-4', type: 'doc.received', ref: 'many' },
          [1, 2, 3].map((n): [string, string, string, Buffer] => ['scans', `${n}.pdf`, 'application/pdf', Buffer.from(`%PDF-${n}`)]),
        );
        assert.equal((await f.send(many)).status, 400);
        // A part for a field the command does not have is refused, not dropped.
        const stray = f.body({ id: 'evt-5', type: 'doc.received', ref: 'stray' }, [['other', 'a.pdf', 'application/pdf', PDF]]);
        assert.equal((await f.send(stray)).status, 404);
        assert.equal((await f.rows()).length, 0);
      });
    });

    test('an unsigned or tampered multipart body is 401 and stores nothing', async () => {
      await fixture(dialect, async (f) => {
        const made = f.body({ id: 'evt-6', type: 'doc.received', ref: 'forged' }, [['scans', 'a.pdf', 'application/pdf', PDF]]);
        assert.equal((await f.send(made, { signed: false })).status, 401);
        // Signed over other bytes: the file in the body is not the one that was signed.
        const other = f.body({ id: 'evt-6', type: 'doc.received', ref: 'forged' }, [
          ['scans', 'a.pdf', 'application/pdf', Buffer.from('%PDF-1.7 swapped')],
        ]);
        assert.equal((await f.send(made, { signed: other.body })).status, 401);
        const tampered = Buffer.from(made.body);
        tampered[tampered.indexOf(PDF) + 6] ^= 1;
        assert.equal((await f.send({ body: tampered, type: made.type }, { signed: made.body })).status, 401);
        assert.equal((await f.rows()).length, 0);
      });
    });
  });
