type Engine = 'sqlite' | 'postgres';
const ENGINES: Engine[] = ['sqlite', 'postgres'];
const skipOf = (engine: Engine) => (engine === 'postgres' ? liveSkip('postgres', process.env.TABLEWALK_TEST_PG) : false);

/* The same rows on both engines; a new row's key is the database's to give. */
const schemaSql = (engine: Engine) => `CREATE TABLE orders (id INTEGER PRIMARY KEY, title TEXT NOT NULL);
  CREATE TABLE audit_event (id ${engine === 'sqlite' ? 'INTEGER PRIMARY KEY' : 'INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY'},
    kind TEXT NOT NULL, correlation_id INTEGER, note TEXT NOT NULL, at DATE NOT NULL, state TEXT NOT NULL DEFAULT 'open', owner TEXT);
  INSERT INTO orders VALUES (1, 'Order one'), (2, 'Order two');
  INSERT INTO audit_event (id, kind, correlation_id, note, at, state, owner) VALUES
    (1, 'order', 1, 'placed', '2026-01-01', 'open', 'bob@example.test'),
    (2, 'order', 1, 'paid', '2026-01-02', 'open', 'bob@example.test'),
    (3, 'conversation', 1, 'hello', '2026-01-03', 'open', 'bob@example.test'),
    (4, 'order', 2, 'shipped', '2026-01-04', 'open', 'bob@example.test');`;

/* The rows of kind order, and the one row of order 1's correlation id that is a conversation's. */
const ORDER_EVENTS = [1, 2, 4];
const OUTSIDE = 3;

const definition = (engine: Engine) => {
  const physical = engine === 'postgres' ? 'public.audit_event' : 'audit_event';
  return {
    id: 'narrowed-writes',
    name: 'Narrowed writes',
    connection: 'narrowed',
    resources: {
      orders: {},
      audit_event: { access: 'write', delete: true },
      orderEvents: {
        physical,
        query: 'kind = order',
        access: 'write',
        delete: true,
        import: true,
        references: { correlation_id: { to: 'orders' } },
        actions: { flag: { label: 'Flag', set: { note: 'flagged' } } },
        machine: { column: 'state', states: { open: { on: { close: { to: 'closed' } } }, closed: { final: true } } },
        notify: [{ on: 'insert', to: 'owner', title: 'Order event: {note}' }],
      },
      chatEvents: { physical, query: 'kind = conversation' },
      // Not plain equalities: its rows can be changed, but a new one's values cannot be read off its query.
      earlyEvents: { physical, query: 'at < 2026-01-03', access: 'write' },
    },
    auth: { roles: { member: { read: true, write: true } } },
    views: {
      'order-events': { kind: 'list', from: 'orderEvents', label: 'Order events' },
      'early-events': { kind: 'list', from: 'earlyEvents', label: 'Early events' },
    },
    home: 'order-events',
    nav: ['order-events', 'early-events'],
  };
};

type Answer = { status: number; text: string; body: any };
type Call = (path: string, body?: object) => Promise<Answer>;
type Sql = (text: string) => Promise<Record<string, unknown>[]>;

/** The fixture served over a database of the test's own on `engine`, signed in as ann; `sql` reads it directly. */
async function serve(engine: Engine, run: (call: Call, sql: Sql, registry: Registry) => Promise<void>) {
  const directory = mkdtempSync(join(tmpdir(), 'mistri-narrowed-writes-'));
  let url: string;
  let drop = async () => {};
  if (engine === 'sqlite') {
    url = join(directory, 'narrowed.db');
    const db = new DatabaseSync(url);
    db.exec(schemaSql(engine));
    db.close();
    provisionSqliteInbox(url);
  } else {
    const owned = await uuidPostgresDatabase('tw_narrowed_writes');
    url = owned.url;
    drop = owned.drop;
    const client = await pgClient(url);
    try {
      await client.query(schemaSql(engine));
    } finally {
      await client.end();
    }
    await provisionPostgresInbox(url);
  }
  const sql: Sql = async (text) => {
    if (engine === 'sqlite') {
      const db = new DatabaseSync(url);
      try {
        return db
          .prepare(text)
          .all()
          .map((row) => ({ ...row }));
      } finally {
        db.close();
      }
    }
    const client = await pgClient(url);
    try {
      return (await client.query(postgresRuntimeSql(text))).rows as Record<string, unknown>[];
    } finally {
      await client.end();
    }
  };
  const registry = new Registry();
  registry.add({ id: 'narrowed', name: 'Narrowed', url, source: 'config', writable: true });
  clearJournal('narrowed');
  const parsed = parseAppConfig(definition(engine), 'narrowed writes fixture');
  const host: AppHost = {
    app: { path: 'narrowed-writes.ts', app: parsed, pages: [], sources: {} },
    pages: [],
    auth: {
      spec: parsed.auth!,
      store: 'not-used',
      handler: async () => {},
      close: async () => {},
      session: async () => ({ id: 'account-ann', who: 'ann@example.test', role: 'member' }),
    },
  };
  const bound = { host: '127.0.0.1', port: 0 };
  const server = createApp({ registry, bound, apps: [host], pages: [] });
  server.listen(0, bound.host);
  await once(server, 'listening');
  const address = server.address();
  assert.ok(address && typeof address === 'object');
  bound.port = address.port;
  try {
    await run(
      async (path, body) => {
        const response = await fetch(`http://${bound.host}:${bound.port}${path}`, {
          signal: AbortSignal.timeout(10_000),
          headers: { 'Content-Type': 'application/json' },
          ...(body ? { method: 'POST', body: JSON.stringify({ app: parsed.id, ...body }) } : {}),
        });
        const text = await response.text();
        let json: unknown;
        try {
          json = JSON.parse(text);
        } catch {
          json = undefined;
        }
        return { status: response.status, text, body: json };
      },
      sql,
      registry,
    );
  } finally {
    const closed = new Promise<void>((resolve) => server.close(() => resolve()));
    server.closeAllConnections();
    await closed;
    await registry.closeAll();
    clearJournal('narrowed');
    await drop();
    rmSync(directory, { recursive: true, force: true });
  }
}

const ok = (answer: Answer, what: string) => assert.equal(answer.status, 200, `${what}: ${answer.text}`);
const refused = (answer: Answer, what: string, said?: RegExp) => {
  assert.ok(answer.status >= 400, `${what} was answered: ${answer.status} ${answer.text}`);
  if (said) assert.match(String(answer.body?.error ?? answer.text), said, what);
};
type Row = { id: number; kind: string; note: string; state: string };
const row = async (sql: Sql, id: number): Promise<Row | undefined> =>
  (await sql(`SELECT id, kind, note, state FROM audit_event WHERE id = ${id}`)).map(
    (found) => ({ ...found, id: Number(found.id) }) as Row,
  )[0];
const kinds = async (sql: Sql) =>
  (await sql('SELECT id, kind FROM audit_event ORDER BY id')).map((found) => `${Number(found.id)}:${String(found.kind)}`);

for (const engine of ENGINES) {
  test(`New and Save keep a row inside the query (${engine})`, { skip: skipOf(engine), timeout: 120_000 }, async () => {
    await serve(engine, async (call, sql) => {
      // An insert takes the query's equality: no kind given, kind = order stored.
      const added = await call('/api/insert', {
        table: 'orderEvents',
        values: { correlation_id: 2, note: 'refunded', at: '2026-01-05', owner: 'bob@example.test' },
      });
      ok(added, 'insert');
      const key = Number(added.body.key?.id ?? added.body.row?.id);
      assert.ok(key > 0, added.text);
      assert.deepEqual(await row(sql, key), { id: key, kind: 'order', note: 'refunded', state: 'open' });
      // The same value given is the value it fixes; another is refused, and nothing is added.
      ok(await call('/api/insert', { table: 'orderEvents', values: { kind: 'order', note: 'again', at: '2026-01-06' } }), 'same kind');
      const before = await kinds(sql);
      refused(
        await call('/api/insert', { table: 'orderEvents', values: { kind: 'conversation', note: 'x', at: '2026-01-07' } }),
        'contradicting insert',
        /orderEvents.*holds only rows where kind = "order"/,
      );
      assert.deepEqual(await kinds(sql), before);
      // A query of a range cannot say what a new row holds.
      refused(
        await call('/api/insert', { table: 'earlyEvents', values: { kind: 'order', note: 'x', at: '2026-01-01' } }),
        'insert under a range',
        /cannot add a row: its query says more of "at" than one value/,
      );
      assert.deepEqual(await kinds(sql), before);

      // An update that keeps the row inside is made; one that moves it out is refused and changes nothing.
      ok(await call('/api/update', { table: 'orderEvents', key: { id: 1 }, values: { note: 'placed again' } }), 'update inside');
      refused(
        await call('/api/update', { table: 'orderEvents', key: { id: 1 }, values: { kind: 'conversation' } }),
        'update out by equality',
        /would move the row out/,
      );
      // A range the new values break: the write is read again on the query, and rolled back.
      refused(
        await call('/api/update', { table: 'earlyEvents', key: { id: 1 }, values: { at: '2026-02-01' } }),
        'update out of a range',
        /out of the rows its query reads/,
      );
      assert.deepEqual(await row(sql, 1), { id: 1, kind: 'order', note: 'placed again', state: 'open' });

      // A row outside the query is answered as a key nothing holds is.
      const outside = await call('/api/update', { table: 'orderEvents', key: { id: OUTSIDE }, values: { note: 'hijacked' } });
      const nothing = await call('/api/update', { table: 'orderEvents', key: { id: 999 }, values: { note: 'hijacked' } });
      assert.equal(outside.status, nothing.status, `${outside.text} / ${nothing.text}`);
      refused(outside, 'update outside');
      assert.equal((await row(sql, OUTSIDE))?.note, 'hello');
      // The table's own resource writes every row as before.
      ok(await call('/api/update', { table: 'audit_event', key: { id: OUTSIDE }, values: { note: 'hello again' } }), 'table update');
    });
  });

  test(
    `Delete, an action, a machine's step and an import stay inside the query (${engine})`,
    { skip: skipOf(engine), timeout: 120_000 },
    async () => {
      await serve(engine, async (call, sql) => {
        // Delete: inside goes, outside answers as missing and stays.
        const outside = await call('/api/delete', { table: 'orderEvents', key: { id: OUTSIDE }, confirm: true });
        const nothing = await call('/api/delete', { table: 'orderEvents', key: { id: 999 }, confirm: true });
        assert.equal(outside.status, nothing.status, `${outside.text} / ${nothing.text}`);
        refused(outside, 'delete outside');
        assert.ok(await row(sql, OUTSIDE), 'the conversation row is still there');
        ok(await call('/api/delete', { table: 'orderEvents', key: { id: 4 }, confirm: true }), 'delete inside');
        assert.equal(await row(sql, 4), undefined);

        // A fixed action is its `set`, through the update route: on a row inside, and not on one outside.
        ok(await call('/api/update', { table: 'orderEvents', key: { id: 2 }, values: { note: 'flagged' } }), 'action inside');
        refused(await call('/api/update', { table: 'orderEvents', key: { id: OUTSIDE }, values: { note: 'flagged' } }), 'action outside');
        assert.equal((await row(sql, OUTSIDE))?.note, 'hello');

        // A machine's step: along its edge on a row inside; the same step on a row outside finds no row.
        ok(await call('/api/update', { table: 'orderEvents', key: { id: 2 }, values: { state: 'closed' } }), 'machine step');
        assert.equal((await row(sql, 2))?.state, 'closed');
        refused(await call('/api/update', { table: 'orderEvents', key: { id: OUTSIDE }, values: { state: 'closed' } }), 'step outside');
        assert.equal((await row(sql, OUTSIDE))?.state, 'open');

        // A CSV import adds its rows inside the query: kind is the query's, never the file's to choose.
        const csv = 'Note,At,Owner\nimported one,2026-02-01,bob@example.test\nimported two,2026-02-02,bob@example.test';
        const mapping = ['note', 'at', 'owner'];
        const checked = await call('/api/import', { table: 'orderEvents', csv, mapping, mode: 'check' });
        ok(checked, 'import check');
        const committed = await call('/api/import', { table: 'orderEvents', csv, mapping, mode: 'commit' });
        ok(committed, 'import commit');
        assert.equal(committed.body.outcome, 'applied', committed.text);
        assert.deepEqual(
          (await sql("SELECT kind FROM audit_event WHERE note LIKE 'imported%' ORDER BY id")).map((found) => found.kind),
          ['order', 'order'],
        );
        const contradicting = await call('/api/import', {
          table: 'orderEvents',
          csv: 'Note,At,Kind\nsneaked,2026-02-03,conversation',
          mapping: ['note', 'at', 'kind'],
          mode: 'commit',
        });
        assert.notEqual(contradicting.body?.outcome, 'applied', contradicting.text);
        assert.deepEqual(await sql("SELECT id FROM audit_event WHERE note = 'sneaked'"), []);
      });
    },
  );

  test(
    `a notify rule on a narrowed resource tells about the rows its query reads alone (${engine})`,
    { skip: skipOf(engine), timeout: 120_000 },
    async () => {
      await serve(engine, async (call, sql) => {
        const notices = async () =>
          (await sql(`SELECT resource, title FROM "${INBOX_TABLES.notice}" ORDER BY id`)).map(
            (found) => `${found.resource}: ${found.title}`,
          );
        // Through the narrowed resource: inside, so told.
        ok(
          await call('/api/insert', { table: 'orderEvents', values: { note: 'one', at: '2026-03-01', owner: 'bob@example.test' } }),
          'one',
        );
        // Through the table's own resource, a row of the query: the rule hears its table's every write, and holds it to the query.
        ok(
          await call('/api/insert', {
            table: 'audit_event',
            values: { kind: 'order', note: 'two', at: '2026-03-02', owner: 'bob@example.test' },
          }),
          'two',
        );
        // A conversation's row is not one of the resource's: nobody is told.
        ok(
          await call('/api/insert', {
            table: 'audit_event',
            values: { kind: 'conversation', note: 'three', at: '2026-03-03', owner: 'bob@example.test' },
          }),
          'three',
        );
        assert.deepEqual(await notices(), ['orderEvents: Order event: one', 'orderEvents: Order event: two']);
      });
    },
  );

  test(
    `a command's transaction writes through a narrowed resource inside its query (${engine})`,
    { skip: skipOf(engine), timeout: 120_000 },
    async () => {
      await serve(engine, async (_call, sql, registry) => {
        const opened = await registry.open('narrowed');
        const physical = engine === 'postgres' ? 'public.audit_event' : 'audit_event';
        const resources = createAppResources(opened.adapter, opened.schema, { orderEvents: physical }, [], [], {
          orderEvents: 'kind = order',
        });
        assert.ok(resources.adapter.transaction, 'the adapter runs transactions');
        const failure = async (write: Promise<unknown>) => {
          try {
            await write;
          } catch (error) {
            return error instanceof Error ? error.message : String(error);
          }
          return 'no failure';
        };
        // Each refusal in its own transaction: a refused write rolls back what its transaction did.
        const inTx = <T>(run: Parameters<NonNullable<typeof resources.adapter.transaction>>[0]) =>
          resources.adapter.transaction!(run) as Promise<T>;
        const added = await inTx<{ key: Record<string, unknown> }>((tx) =>
          tx.insert({ table: 'orderEvents', values: { note: 'by command', at: '2026-04-01' } }),
        );
        assert.equal((await row(sql, Number(added.key.id)))?.kind, 'order');
        assert.match(
          await failure(inTx((tx) => tx.insert({ table: 'orderEvents', values: { kind: 'conversation', note: 'x', at: '2026-04-02' } }))),
          /holds only rows where kind = "order"/,
        );
        assert.match(
          await failure(inTx((tx) => tx.update({ table: 'orderEvents', key: { id: 1 }, values: { kind: 'conversation' } }))),
          /would move the row out/,
        );
        assert.equal((await row(sql, 1))?.kind, 'order');
        await inTx((tx) => tx.update({ table: 'orderEvents', key: { id: 1 }, values: { note: 'by command' } }));
        assert.equal((await row(sql, 1))?.note, 'by command');
        // Outside the query: the adapter's own answer for a key nothing holds, for an update and a delete.
        const missingUpdate = await failure(inTx((tx) => tx.update({ table: 'orderEvents', key: { id: 999 }, values: { note: 'x' } })));
        assert.equal(
          await failure(inTx((tx) => tx.update({ table: 'orderEvents', key: { id: OUTSIDE }, values: { note: 'x' } }))),
          missingUpdate,
        );
        const missingDelete = await failure(inTx((tx) => tx.remove({ table: 'orderEvents', key: { id: 999 } })));
        assert.equal(await failure(inTx((tx) => tx.remove({ table: 'orderEvents', key: { id: OUTSIDE } }))), missingDelete);
        assert.ok(await row(sql, OUTSIDE));
        await inTx((tx) => tx.remove({ table: 'orderEvents', key: { id: 2 } }));
        assert.equal(await row(sql, 2), undefined);
        // A write outside a transaction is held inside the query the same way.
        assert.match(
          await failure(resources.adapter.update!({ table: 'orderEvents', key: { id: 1 }, values: { kind: 'conversation' } })),
          /would move the row out/,
        );
        assert.deepEqual(ORDER_EVENTS.includes(1), true);
      });
    },
  );

  test(
    `the App API's generic writes take a narrowed resource, its query's columns given by the query (${engine})`,
    { skip: skipOf(engine), timeout: 120_000 },
    async () => {
      await serve(engine, async (_call, _sql, registry) => {
        const { connection: _connection, ...rest } = definition(engine);
        const exposed = (fields: string[]) =>
          parseAppConfig(
            {
              ...rest,
              sources: { business: { connection: 'narrowed', default: true } },
              api: { version: 1, roles: ['member'], resources: { orderEvents: { fields, create: true, update: true, delete: true } } },
            },
            'api fixture',
          );
        /* Loading checks the exposure (assertApiWrites): `kind` is NOT NULL and not exposed, and the query sets it.
         The generic write runs as a command, through the same transaction the command test above writes in. */
        const app = exposed(['id', 'note', 'at', 'owner']);
        const resources = await loadAppRuntimeResources(registry, app, 'narrowed');
        assert.deepEqual(apiWriteProblems(app, resources.schema), []);
        // Through the table's own resource the same exposure must name it.
        const plain = parseAppConfig(
          {
            ...rest,
            sources: { business: { connection: 'narrowed', default: true } },
            api: { version: 1, roles: ['member'], resources: { audit_event: { fields: ['id', 'note', 'at', 'owner'], create: true } } },
          },
          'api fixture',
        );
        assert.match(apiWriteProblems(plain, resources.schema).join(' '), /needs "kind"/);
      });
    },
  );
}
