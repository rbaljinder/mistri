test('a props type is named for its component, and written once for each kind of component', () => {
  assert.equal(propsTypeName('sales-summary'), 'SalesSummaryProps');
  assert.equal(propsTypeName('bin-map'), 'BinMapProps');
  assert.equal(propsTypeName('ticket'), 'TicketProps');
  const types = componentTypes(app, pages, 'Helpdesk', true)!;
  assert.match(types, /^\/\/ Generated by `mistri check --app <app>` from the "Helpdesk" app's component declarations\.$/m);
  assert.match(types, /^export type TicketBoardProps = /m);
  assert.match(types, /^export type StatusDotProps = ValueProps<Cell<"ticket", "status">, Rows\["ticket"\]>;$/m);
  assert.match(types, /^export type ReplyStreamProps = ListProps<\{ from: "reply"; presentation: /m);
  assert.equal(
    componentTypes(
      parseAppConfig({ name: 'Plain', resources: { ticket: {} }, views: { t: { kind: 'list', from: 'ticket' } }, home: 't' }, 'f'),
      [],
      'Plain',
      true,
    ),
    undefined,
  );
});

function compile(source: string) {
  const dir = mkdtempSync(join(ROOT, 'test', '.components-typing-'));
  try {
    writeFileSync(join(dir, 'mistri-schema.d.ts'), typesForSchema(SCHEMA));
    writeFileSync(join(dir, 'mistri-components.d.ts'), componentTypes(app, pages, 'Helpdesk', true)!);
    writeFileSync(join(dir, 'module.ts'), source);
    return spawnSync(
      process.execPath,
      [
        join(ROOT, 'node_modules/typescript/bin/tsc'),
        '--noEmit',
        '--ignoreConfig',
        '--strict',
        '--skipLibCheck',
        '--module',
        'nodenext',
        '--moduleResolution',
        'nodenext',
        '--allowImportingTsExtensions',
        '--target',
        'es2022',
        '--pretty',
        'false',
        join(dir, 'module.ts'),
      ],
      { cwd: ROOT, encoding: 'utf8', timeout: 120_000 },
    );
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test('a component imports its props type: reads, figures and props are typed from the declaration', () => {
  const fine = compile(`
    import type { TicketBoardProps, TicketThreadProps, StatusDotProps, ReplyStreamProps } from './mistri-components.d.ts';
    export function Thread(p: TicketThreadProps) {
      if (p.rows.replies) {
        const body: string = p.rows.replies[0].body;
        const cost: string | null = p.rows.replies[0].cost;
      }
      if (p.figures.replies !== undefined) { const replies: number = p.figures.replies; }
      if (p.figures.spent !== undefined) {
        // @ts-expect-error a sum may be a string or null
        const spent: number = p.figures.spent;
        const said: number | string | null = p.figures.spent;
      }
    }
    export function Board(p: TicketBoardProps) {
      if (p.rows.recent) {
        const subject: string | null = p.rows.recent[0].subject;
        // @ts-expect-error the dashboard read shows id and subject, nothing else
        p.rows.recent[0].status;
      }
      // a count is always a number
      if (p.figures.open !== undefined) { const open: number = p.figures.open; }
      if (p.figures.byStatus) { const first: { key: unknown; value: number; label?: string } = p.figures.byStatus[0]; }
      const rowsLeft: number | undefined = p.props.rows;
      const tone: 'calm' | 'loud' | undefined = p.props.tone;
      // @ts-expect-error no such prop is declared
      p.props.colour;
    }
    export const dot = (p: StatusDotProps) => { const value: string = p.value; };
    export const list = (p: ReplyStreamProps) => { const body: string = p.rows[0].body; };
  `);
  assert.equal(fine.status, 0, fine.stdout + fine.stderr);
  const typo = compile(`
    import type { TicketBoardProps } from './mistri-components.d.ts';
    export const f = (p: TicketBoardProps) => p.figures.nope;
  `);
  assert.notEqual(typo.status, 0, 'a total the declaration does not make is a type error');
});
