test('a rollup the types cannot hold is refused by name, never left out of them', async () => {
  // Two references from line to product and no `whose`: the refusal names both.
  await assert.rejects(
    typesOfApp(shopApp({ lines: { fn: 'count', from: 'line' } }), shop, ['shop']),
    /rollups "lines": "line" points at "product" through product_id, alt_id\. Say which with "whose"\./,
  );
  // A rollup of a hidden column is served to no reader, so no page could show it.
  const hiddenAmount = parseAppConfig(
    {
      name: 'Shop',
      resources: {
        product: { rollups: { spent: { fn: 'sum', from: 'line', column: 'amount', whose: 'product_id' } } },
        line: { hidden: ['amount'] },
      },
      views: { products: { kind: 'list', from: 'product' } },
      home: 'products',
    },
    'test',
  );
  await assert.rejects(
    typesOfApp(hiddenAmount, shop, ['shop']),
    /resources "product", rollups "spent" reads a column or reference no reader is served/,
  );
});

/* R6: a refused App is typed from what it declares, so the typecheck beside its one problem is not a screen of "not a
   column": a segment refused for its name (`today`, refused on upgrade) or its conditions keeps its word in the types,
   and tags whose rule does not resolve still type the record's `tags`. */
test('a refused segment and refused tags are still typed by what they declare', async () => {
  const app = parseAppConfig(
    {
      name: 'Shop',
      resources: {
        product: {
          segments: { today: 'price > 10', cheap: 'price < 5', broken: 'nowhere > 1' },
          tags: { through: 'ledger', to: 'migration_marker' },
        },
        ledger: {},
        line: {},
        migration_marker: {},
      },
      views: { products: { kind: 'list', from: 'product' } },
      home: 'products',
    },
    'test',
  );
  const types = await typesOfApp(app, shop, ['shop']);
  const segments = /\n {2}product: ([^\n]*);/.exec(types.slice(types.indexOf('export type Segments')))?.[1] ?? '';
  for (const name of ['today', 'cheap', 'broken']) assert.match(segments, new RegExp(`"${name}"`), types);
  assert.match(types, /^ {2}product: "id" \| "name" \| "cost" \| "price" \| "tags";$/m, types);
});
