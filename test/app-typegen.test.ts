function table(schema: string, name: string): TableMeta {
  return {
    id: `${schema}.${name}`,
    schema,
    name,
    isView: false,
    columns: [
      { name: 'id', type: 'integer', primaryKey: true, nullable: false },
      { name: 'name', type: 'text', primaryKey: false, nullable: false },
    ],
  };
}

const physical: DatabaseSchema = {
  label: 'Postgres',
  dialect: 'postgres',
  readAt: '2026-09-06',
  tables: [table('public', 'incident'), table('archive', 'incident')],
  // An archived incident is its live one's: the reference a related list's `whose` follows.
  foreignKeys: [
    {
      name: 'archived_incident_fkey',
      from: { table: 'archive.incident', columns: ['id'] },
      to: { table: 'public.incident', columns: ['id'] },
    },
  ],
};

function database(file: string) {
  const db = new DatabaseSync(file);
  db.exec('CREATE TABLE physical_ticket (id INTEGER PRIMARY KEY, name TEXT NOT NULL)');
  db.close();
}

